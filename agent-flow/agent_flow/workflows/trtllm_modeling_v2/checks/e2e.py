"""Tests of datasets: the target's generated e2e test, run by the tree's own runner.

A test of datasets (``spec/verification.py``) runs, at each member, one engine
that goes through its datasets in order: the boot prompts (``generate``), the
benchmarks (``accuracy_core``) and a speculator's acceptance. The tree runs it,
not the flow: per target the flow writes two files into the tree
(:func:`write_generated`), and commits them at the start of the run::

    tests/integration/defs/accuracy/modeling_v2/<family>/<target>/
      test_e2e.py       a fixed thin test (:func:`render_test`)
      e2e_cases.yaml    one case per check of a test of datasets (:func:`build_cases`)

``tests/integration/defs/accuracy/modeling_v2/_e2e.py`` loads the cases and
runs one (``load_cases``, ``run_case``). CI runs the same file from a test list,
judged by the references rows alone. A check of the run runs its case's node
(:func:`node_id`) through ``checks/pytest_node.py``, with :data:`RESULTS_ENV`
naming a file the runner writes one JSON line per dataset to, and
:data:`REFERENCES_ENV` giving a dataset the score it is judged against where
the flow judges against a measured anchor (a placeholder row's first score, a
variant's unit's score).

A case is the configuration the flow builds for the feature at the member
(``check_config.check_configuration``: core's settings, the features built up
to it, a variant's overlay, the member's parallelism) with
``modeling_v2: require``. A path under the models root is written as
``${LLM_MODELS_ROOT}/...``, so CI finds the checkpoint under its own root.
"""

