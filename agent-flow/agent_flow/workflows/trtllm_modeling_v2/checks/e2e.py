TEST_FILENAME = "test_e2e.py"
#: Extra checks (``spec/verification.py``): the shared ones beside the runner, and a
#: target's own beside its generated test.
SHARED_EXTRA_CHECKS = f"{ACCURACY_ROOT}/_extra_checks.py"
TARGET_EXTRA_CHECKS = "extra_checks.py"
CASES_FILENAME = "e2e_cases.yaml"
CASES_VERSION = 1
#: The file the runner appends one JSON line per dataset to.
RESULTS_ENV = "MV2FLOW_E2E_RESULTS"
#: A JSON object ``{dataset: score}``: the score a benchmark is judged against instead of its row.
REFERENCES_ENV = "MV2FLOW_E2E_REFERENCES"
#: Comma-separated dataset names: a debugging run's subset of the case (``gate --datasets``).
DATASETS_ENV = "MV2FLOW_E2E_DATASETS"
MODELS_ROOT_ENV = "LLM_MODELS_ROOT"
#: How a case names a path under the models root.
MODELS_ROOT_PREFIX = "${LLM_MODELS_ROOT}"
#: Where the tree's tests read a benchmark's dataset under the models root.
DATASET_DIRS: dict[str, str] = {"gsm8k": "datasets/openai/gsm8k"}
#: The message of the flow's own commit of the generated files.
COMMIT_SUBJECT = "[None][test] {target}: the e2e test the trtllm_modeling_v2 run generated"

