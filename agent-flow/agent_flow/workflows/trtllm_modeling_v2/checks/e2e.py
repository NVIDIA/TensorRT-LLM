#: The year the generated files' copyright header carries.
COPYRIGHT_YEAR = 2026


def target_dir(family: str, target: str) -> str:
    """Where the target's accuracy tests live, relative to the repository."""
    return f"{ACCURACY_ROOT}/{family}/{Path(target).name}"


def generated_paths(family: str, target: str) -> tuple[str, str]:
    """The generated test and its cases, relative to the repository."""
    where = target_dir(family, target)
    return f"{where}/{TEST_FILENAME}", f"{where}/{CASES_FILENAME}"


def extra_check_files(family: str, target: str) -> tuple[str, str]:
    """Where a test's extra checks are looked up, in order: the target's own file, then the shared one."""
    return f"{target_dir(family, target)}/{TARGET_EXTRA_CHECKS}", SHARED_EXTRA_CHECKS


def resolve_extra_checks(
    repo: str | Path, family: str, target: str, names: Iterable[str]
) -> tuple[dict[str, str], list[str]]:
    """Each of ``names`` to where it is defined (``<file>::<name>``), and what could not be.

    Looked up in :func:`extra_check_files`; read from the source, nothing imported.
    """
    files = extra_check_files(family, target)
    found: dict[str, str] = {}
    problems: list[str] = []
    for name in names:
        node, said = extra_check_function(repo, files, name)
        if node is None:
            problems.append(said)
        else:
            found[name] = node
    return found, problems


def class_name(target: str) -> str:
    """``TestModelingV2<Name>``'s name: the target directory in CamelCase (``glm_5_2__tp8`` -> ``Glm52Tp8``)."""
    return "".join(
        part[:1].upper() + part[1:] for part in re.split(r"_+", Path(target).name) if part
    )


def render_test(target: str) -> str:
    """The generated ``test_e2e.py`` of ``target``."""
    name = Path(target).name
    return _TEST_TEMPLATE.format(year=COPYRIGHT_YEAR, target=name, cls=class_name(name))


def case_id(feature: str, test: str, member: str) -> str:
    """A case's id, its pytest id: ``<feature>-<test>-<member>``."""
    return f"{feature}-{test}-{member}"


def node_id(family: str, target: str, feature: str, test: str, member: str) -> str:
    """The pytest node of one case, relative to the repository."""
    path, _ = generated_paths(family, target)
    return f"{path}::TestModelingV2{class_name(target)}::test_e2e[{case_id(feature, test, member)}]"


# ------------------------------------------------------------------------ cases


def models_root(task_data: Mapping[str, Any]) -> str:
    """The models root the spec's environment names; ``""`` when it names none."""
    environment = task_data.get("environment") or {}
    env = environment.get("env") if isinstance(environment, Mapping) else None
    root = (env or {}).get(MODELS_ROOT_ENV) if isinstance(env, Mapping) else None
    return str(root or "").rstrip("/")


def portable(value: Any, root: str) -> Any:
    """``value`` with every string path under ``root`` written as ``${LLM_MODELS_ROOT}/...``."""
    if isinstance(value, Mapping):
        return {str(k): portable(v, root) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [portable(v, root) for v in value]
    if root and isinstance(value, str) and (value == root or value.startswith(root + "/")):
        return MODELS_ROOT_PREFIX + value[len(root) :]
    return value


def _generate(spec: Mapping[str, Any], config: Mapping[str, Any], feature: str, features) -> dict:
    """The ``generate`` dataset: the boot prompts, a prompt the engine must split, the reuse probe."""
    boot = resolve_boot_spec(spec, feature, features)
    prompts: list[Any] = list(boot.prompts)
    for item in boot.items:
        prompt: dict[str, Any] = {"prompt": item.prompt}
        if item.images:
            prompt.update(images=list(item.images), render=item.render)
        prompts.append(prompt)
    limits = check_config.EngineLimits.from_config(config)
    chunk = None
    if check_config.sets_chunking(spec, feature) and limits.chunked_prefill:
        chunk = chunk_probe_tokens(limits.max_num_tokens, limits.max_seq_len)
        if chunk is None:
            raise ValueError(
                f"{feature} is about chunked prefill, and its engine's limits (max_num_tokens "
                f"{limits.max_num_tokens}, max_seq_len {limits.max_seq_len}) leave no room "
                "for a prompt the engine would have to split"
            )
    kv = config["llm"].get("kv_cache_config") or {}
    return {
        "name": DATASET_GENERATE,
        "kind": "generate",
        "prompts": prompts,
        "max_tokens": boot.max_tokens,
        "apply_chat_template": bool(config.get("apply_chat_template")),
        "chunk_probe_tokens": chunk,
        "reuse_probe": bool(kv.get("enable_block_reuse")),
    }


def _benchmark(spec: Mapping[str, Any], name: str, test: Test) -> dict:
    """A benchmark dataset: its ``accuracy_core`` task, under the spec's protocol as ``test`` changes it."""
    kwargs = dict((spec.get("accuracy") or {}).get("evaluator_kwargs") or {})
    kwargs.update(test.evaluator_kwargs or {})
    dataset = {
        "name": name,
        "kind": "benchmark",
        "task": BENCHMARKS[name],
        "extra_acc_spec": None,
        "evaluator_kwargs": kwargs,
    }
    return dataset


def _acceptance(
    spec: Mapping[str, Any],
    config: Mapping[str, Any],
    feature: str,
    features,
    root: str,
    *,
    benchmark: str = "gsm8k",
) -> dict:
    accuracy = spec.get("accuracy") or {}
    workload = acceptance_checks.resolve_acceptance_workload(accuracy, feature, benchmark=benchmark)
    floor = acceptance_checks.resolve_acceptance_floor_spec(accuracy, feature, features)
    load: dict[str, Any] = {
        "max_tokens": workload.max_tokens,
        "apply_chat_template": bool(config.get("apply_chat_template")),
    }
    if workload.prompts:
        load["prompts"] = list(workload.prompts)
    else:
        dataset = dict(workload.dataset or {})
        known = {
            name: f"{MODELS_ROOT_PREFIX}/{where}"
            for name, where in DATASET_DIRS.items()
            if root and workload_io.KNOWN_DATASETS.get(name, {}).get("source") == dataset["source"]
        }
        if known:
            dataset["source"] = next(iter(known.values()))
        load["dataset"] = dataset
    return {
        "name": DATASET_ACCEPTANCE,
        "kind": "acceptance",
        "workload": load,
        "min_draft_iterations": workload.min_draft_iterations,
        "floor": None if floor is None else round(floor.value, 6),
        "floor_source": "" if floor is None else str(floor.source or ""),
    }


def build_case(
    environment: RunEnvironment,
    spec: Mapping[str, Any],
    test: Test,
    member: str,
    features: Sequence[str],
    extra_checks: Mapping[str, str] | None = None,
) -> dict[str, Any]:
    """The case of ``test`` at ``member``: its engine's options and its datasets, in order.

    ``spec`` is the one ``test``'s feature runs under (a variant's with its
    overlay), and ``features`` those its target implements. The test's own
    ``config`` is laid over the engine's options last. ``extra_checks`` gives where
    each of the test's extra checks is defined (:func:`resolve_extra_checks`).
    """
    feature = test.feature
    config = check_config.check_configuration(
        spec, environment, unit=feature, features=features, max_tokens=32, member=member
    )
    accuracy = spec.get("accuracy") or {}
    llm = dict(config["llm"])
    llm.pop("model", None)
    llm["modeling_v2"] = MODE_REQUIRE
    for key in ("max_seq_len", "max_batch_size"):
        if accuracy.get(key) is not None:
            llm[key] = accuracy[key]
    if accuracy.get("max_batch_size") is not None:
        # A benchmark's batch is a global total too: each attention-DP rank serves its share.
        check_config.share_batch(llm, member, llm.get("tensor_parallel_size"))
    if test.config:
        # The test's own options are the engine's last word, and its probes' limits.
        llm = check_config.merge_options(llm, test.config)
        config = {**config, "llm": check_config.merge_options(config["llm"], test.config)}
    sampling = {k: v for k, v in config["sampling"].items() if k != "max_tokens"}
    root = models_root(spec)
    datasets: list[dict[str, Any]] = []
    for name in test.datasets:
        if name == DATASET_GENERATE:
            datasets.append(_generate(spec, config, feature, features))
        elif name == DATASET_ACCEPTANCE:
            bench = test.benchmarks[0] if test.benchmarks else "gsm8k"
            datasets.append(_acceptance(spec, config, feature, features, root, benchmark=bench))
        else:
            datasets.append(_benchmark(spec, name, test))
    _, size = parse_parallel_segment(member)
    case = {
        "id": case_id(feature, test.name, member),
        "feature": feature,
        "test": test.name,
        "member": member,
        "devices": int(size or environment.world_size or 1),
        "llm": portable(llm, root),
        "sampling": sampling,
        "datasets": portable(datasets, root),
    }
    if test.extra_checks:
        where = dict(extra_checks or {})
        unfound = [name for name in test.extra_checks if name not in where]
        if unfound:
            raise ValueError(
                f"{test.feature}.{test.name}: extra check(s) {unfound} were not looked up in the tree"
            )
        case["extra_checks"] = [{"check": where[name]} for name in test.extra_checks]
    return case


def build_cases(
    task_data: Mapping[str, Any],
    model_name: str,
    cases: Iterable[Mapping[str, Any]],
) -> dict[str, Any]:
    """The whole ``e2e_cases.yaml``: the model, and ``cases`` in order."""
    root = models_root(task_data)
    return {
        "version": CASES_VERSION,
        "model_name": model_name,
        "model_dir": portable(str(task_data["checkpoint_path"]).rstrip("/"), root),
        "cases": [dict(c) for c in cases],
    }


def render_cases(document: Mapping[str, Any]) -> str:
    """``e2e_cases.yaml``'s text."""
    header = (
        "# Generated by the trtllm_modeling_v2 agent flow from its spec (`verification`): "
        "change the spec,\n# not this file. Read by test_e2e.py beside it "
        "(tests/integration/defs/accuracy/modeling_v2/_e2e.py).\n"
    )
    return header + yaml.safe_dump(dict(document), sort_keys=False, width=100)


def write_generated(
    repo: str | Path, family: str, target: str, document: Mapping[str, Any]
) -> list[str]:
    """Write the target's generated test and cases into ``repo``; the paths that changed.

    The target's test directory gets an empty ``__init__.py`` when it has none.
    """
    root = Path(repo)
    test_path, cases_path = generated_paths(family, target)
    wanted = {test_path: render_test(target), cases_path: render_cases(document)}
    package = f"{target_dir(family, target)}/__init__.py"
    if not (root / package).is_file():
        wanted[package] = ""
    family_package = f"{ACCURACY_ROOT}/{family}/__init__.py"
    if not (root / family_package).is_file():
        wanted[family_package] = ""
    changed: list[str] = []
    for rel, text in wanted.items():
        path = root / rel
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        changed.append(rel)
    return changed


def commit_generated(
    repo: str | Path, paths: Sequence[str], target: str, identity_env: Mapping[str, str]
) -> str:
    """Commit ``paths`` alone in ``repo``, signed off as the run's identity; the commit, ``""`` if none."""
    if not paths:
        return ""
    env = {**os.environ, **identity_env}

    def git(*args: str) -> subprocess.CompletedProcess:
        return subprocess.run(
            ["git", "-C", str(repo), *args], capture_output=True, text=True, env=env, check=False
        )

    added = git("add", "--", *paths)
    if added.returncode != 0:
        raise RuntimeError(f"git add of the generated tests failed: {added.stderr.strip()}")
    staged = git("diff", "--cached", "--quiet", "--", *paths)
    if staged.returncode == 0:
        return ""
    message = COMMIT_SUBJECT.format(target=Path(target).name) + (
        "\n\nThe test and its cases are generated from the run's spec; the run's agents do not "
        "edit them."
    )
    done = git("commit", "-q", "-s", "-m", message, "--", *paths)
    if done.returncode != 0:
        raise RuntimeError(f"committing the generated tests failed: {done.stderr.strip()}")
    head = git("rev-parse", "HEAD")
    return head.stdout.strip()


