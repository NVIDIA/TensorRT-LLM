def read_results(path: Path) -> list[dict[str, Any]]:
    """The runner's lines in ``path``, one per dataset run; ``[]`` when it wrote none."""
    try:
        text = Path(path).read_text(encoding="utf-8")
    except OSError:
        return []
    out = []
    for line in text.splitlines():
        try:
            data = json.loads(line)
        except ValueError:
            continue
        if isinstance(data, dict):
            out.append(data)
    return out


def describe(line: Mapping[str, Any]) -> str:
    """One dataset's or extra check's line, as a verdict says it; a check that passed says what it saw."""
    name = str(line.get("dataset") or "?")
    verdict = "passed" if line.get("passed") else "FAILED"
    score = line.get("score")
    said = f"{name} {verdict}"
    if isinstance(score, (int, float)):
        said += f" ({score:.4g}"
        threshold = line.get("threshold")
        if isinstance(threshold, (int, float)):
            said += f" vs threshold {threshold:.4g}"
        reference = line.get("reference")
        if isinstance(reference, (int, float)):
            said += f", reference {reference:.4g}"
        said += ")"
    detail = str(line.get("detail") or "").strip()
    if detail and (not line.get("passed") or line.get("kind") == "extra_check"):
        said += f": {detail[:300]}"
    return said


def run_e2e(
    environment: RunEnvironment,
    *,
    task_data: Mapping[str, Any],
    test: Test,
    member: str,
    node: str,
    workdir: str | Path,
    runner: ShellRunner = default_shell_runner,
    references: Mapping[str, float] | None = None,
    env: Mapping[str, str] | None = None,
    datasets: Sequence[str] = (),
) -> tuple[GateResult, list[dict[str, Any]]]:
    """Run ``test``'s case at ``member`` (``node``) and judge it; the verdict and the runner's lines.

    The verdict is the node's (``pytest_node.run_node``), with each dataset's
    line in its detail and the first benchmark's score as ``measured``.
    ``references`` judges a benchmark against a score instead of its row.
    ``datasets`` runs only those of the case: a debugging run, never a check's.
    """
    token = pytest_node.run_token()
    results = (
        gate_workdir(workdir) / f"e2e.{test.feature}.{test.name}.{member}.{token}.results.jsonl"
    )
    variables = {
        **(test.env or {}),
        **(env or {}),
        RESULTS_ENV: str(results),
        "HF_DATASETS_OFFLINE": "1",
        "HF_HUB_OFFLINE": "1",
    }
    if datasets:
        variables[DATASETS_ENV] = ",".join(datasets)
    if references:
        variables[REFERENCES_ENV] = json.dumps(
            {k: float(v) for k, v in references.items()}, sort_keys=True
        )
    result = pytest_node.run_node(
        environment,
        name=test.name,
        node=node,
        task_data=task_data,
        workdir=workdir,
        timeout=test.timeout,
        runner=runner,
        env=variables,
        unit=test.feature,
        member=member,
        what="the e2e test",
        # Every process's record of where it imported the package under test reaches the
        # command's output, as the engine's own prints do.
        capture=False,
        token=token,
        launch_world=True,
    )
    lines = read_results(results)
    if not lines:
        return result, lines
    measured = next(
        (
            float(line["score"])
            for name in test.benchmarks
            for line in lines
            if line.get("dataset") == name and isinstance(line.get("score"), (int, float))
        ),
        None,
    )
    first = next(
        (
            line
            for name in test.benchmarks
            for line in lines
            if line.get("dataset") == name and isinstance(line.get("score"), (int, float))
        ),
        {},
    )
    reference, threshold = first.get("reference"), first.get("threshold")
    detail = "; ".join(describe(line) for line in lines)
    ran = [d for d in (*test.datasets, *test.extra_checks) if not datasets or d in datasets]
    missing = [d for d in ran if d not in {line.get("dataset") for line in lines}]
    if missing:
        detail += f"; no result for {', '.join(missing)} ({result.detail})"
    return (
        replace(
            result,
            detail=detail,
            measured=measured,
            reference=float(reference) if isinstance(reference, (int, float)) else None,
            floor=float(threshold) if isinstance(threshold, (int, float)) else None,
            floor_rule="accuracy_core hypothesis test" if threshold is not None else "",
            explained=True,
        ),
        lines,
    )


def scores(lines: Iterable[Mapping[str, Any]]) -> dict[str, float]:
    """Each benchmark's score in the runner's lines, by dataset."""
    return {
        str(line["dataset"]): float(line["score"])
        for line in lines
        if line.get("kind") == "benchmark" and isinstance(line.get("score"), (int, float))
    }


