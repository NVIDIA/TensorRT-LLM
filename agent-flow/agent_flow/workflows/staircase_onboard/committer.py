"""One safe way for concurrent agents to commit into one worktree.

Smiths run concurrently inside a dependency batch, in the same checkout, and
git's index is a single shared file. The prompts have always told agents to
stage by explicit path and never `git add -A`, and that rule is right but it
is not sufficient. Two failures survived it:

- **`.git/index.lock` contention.** Two agents committing in the same second
  and one gets ``Unable to create '.git/index.lock': File exists``. An agent
  that reads that as "the repo is broken" then does something creative.
- **Cross-attribution.** Staircase measured this twice in one run: 576 lines
  of another agent's in-progress test file and a mid-edit contract landed in
  an unrelated commit, splitting one entry's attribution across two commits
  and leaving dangling cross-references.

The fix is a critical section plus a verification, and neither is judgement,
so neither belongs in a prompt. This module generates a small shell script
into the workspace; the agent prompts hand out its path and nothing else.
What the script guarantees:

1. **Serialized.** An ``flock`` around the whole stage-and-commit, with a
   bounded wait, so concurrency becomes a short queue rather than an error.
2. **Scoped.** ``git commit -- <paths>`` commits the working-tree content of
   exactly those paths on top of ``HEAD``, whatever else sits in the index.
3. **Verified.** After committing it diffs the new commit against its parent
   and **fails** if the file list is not exactly what was asked for. This is
   the part that matters: misattribution stops being something a reviewer
   notices later and becomes something the tool refuses to do.

A private ``GIT_INDEX_FILE`` per dispatch was the other candidate and is a
trap. It does stop one agent's ``add`` from seeing another's staged files,
but an index seeded from ``HEAD`` before a concurrent commit lands produces a
tree that silently *reverts* that commit — trading a visible attribution bug
for an invisible data-loss one.
"""

from __future__ import annotations

import os
import shlex
import stat
from pathlib import Path

#: How long an agent waits for the commit lock before giving up. Generous
#: because the section is milliseconds of git and the alternative — an agent
#: that decides the lock is stale — is much worse than a slow queue.
LOCK_TIMEOUT_S = 300

SCRIPT_NAME = "commit.sh"

_SCRIPT = """#!/usr/bin/env bash
# Generated by the staircase-onboard orchestrator. Do not edit.
#
# usage: {name} <message> <path> [path...]
#
# Commits exactly the named paths, under a lock, and verifies afterwards that
# the commit contains exactly those paths and nothing else.
set -uo pipefail

REPO={repo}
LOCK={lock}
TIMEOUT={timeout}

if [ "$#" -lt 2 ]; then
  echo "usage: $0 <message> <path> [path...]" >&2
  exit 2
fi
MESSAGE="$1"; shift

for path in "$@"; do
  if [ ! -e "$REPO/$path" ] && [ ! -e "$path" ]; then
    echo "commit.sh: $path does not exist; commit by path relative to the repo root" >&2
    exit 2
  fi
done

exec {fd}>"$LOCK"
if ! flock -w "$TIMEOUT" {fd}; then
  echo "commit.sh: waited ${{TIMEOUT}}s for the commit lock and did not get it." >&2
  echo "Another agent is committing. This is a symptom to report, not to work around." >&2
  exit 75
fi

cd "$REPO" || exit 1

# The identity git would use by itself comes before $USER: a login name is
# not a name a DCO sign-off can carry.
COMMIT_NAME=${{STAIRCASE_GIT_NAME:-$(git -C "$REPO" config user.name 2>/dev/null)}}
COMMIT_NAME=${{COMMIT_NAME:-${{USER:-staircase}}}}
COMMIT_EMAIL=${{STAIRCASE_GIT_EMAIL:-$(git -C "$REPO" config user.email 2>/dev/null)}}
COMMIT_EMAIL=${{COMMIT_EMAIL:-${{COMMIT_NAME}}@nvidia.com}}

# `git add` so a new file is known to the index; `git commit -- <paths>` so
# the commit carries the working-tree content of exactly these paths on top
# of HEAD, whatever else another agent has staged.
if ! git add -- "$@"; then
  echo "commit.sh: git add failed" >&2
  exit 1
fi
# Identity passed on the command line, never written to config. `-s` adds
# the DCO sign-off the target repository requires of every commit.
#
# Two independent reasons, both measured. A redirected $HOME (see
# agent_home.py) takes the real ~/.gitconfig off git's search path; and this
# checkout cannot accept `git config --local` at all, because a stale
# `.git/config.lock` on Lustre refuses both `rm` ("Device or resource busy")
# and `chmod` ("Read-only file system"). Without this every commit dies with
#
#   fatal: unable to auto-detect email address (got 'user@host.(none)')
#
# which commit.sh reported as "nothing to commit is the usual cause" --- so
# each of seven concurrent smiths rediscovered it separately and worked
# around it by hand.
if ! git -c user.name="$COMMIT_NAME" -c user.email="$COMMIT_EMAIL" \
     commit -s -q -m "$MESSAGE" -- "$@"; then
  echo "commit.sh: git commit failed (nothing to commit is the usual cause)" >&2
  exit 1
fi

SHA=$(git rev-parse HEAD)
ACTUAL=$(git diff-tree --no-commit-id --name-only -r "$SHA" | LC_ALL=C sort)
WANTED=$(printf '%s\\n' "$@" | LC_ALL=C sort)
if [ "$ACTUAL" != "$WANTED" ]; then
  echo "commit.sh: REFUSING TO LEAVE THIS COMMIT AS IS." >&2
  echo "  asked for:" >&2
  printf '    %s\\n' $WANTED >&2
  echo "  commit $SHA actually contains:" >&2
  printf '    %s\\n' $ACTUAL >&2
  # Single quotes, not double: a backtick inside a double-quoted echo is a
  # command substitution, so writing the reset as an example inside "..."
  # runs it — and then the explicit reset below runs it a second time,
  # rewinding a commit that had nothing to do with this one.
  echo '  Undoing it with: git reset --soft HEAD^' >&2
  echo "  Your work stays in the tree. Report this: it means a path you named" >&2
  echo "  matched more than you meant, or another agent's file was already" >&2
  echo "  staged for one of them." >&2
  git reset --soft HEAD^
  exit 1
fi

echo "commit.sh: $SHA"
printf '  %s\\n' $ACTUAL
"""


def render_script(repo: str | Path, lock: str | Path, *, timeout: int = LOCK_TIMEOUT_S) -> str:
    """The script body, with this run's repo and lock baked in.

    Baked rather than passed so an agent has no argument it can get wrong,
    and so the same call works from any working directory.
    """
    return _SCRIPT.format(
        name=SCRIPT_NAME,
        repo=shlex.quote(str(repo)),
        lock=shlex.quote(str(lock)),
        timeout=int(timeout),
        # An explicit high fd, so the redirect cannot collide with a
        # descriptor the surrounding tool already holds open.
        fd=9,
    )


def install_committer(
    workspace: str | Path, repo: str | Path, *, timeout: int = LOCK_TIMEOUT_S
) -> Path:
    """Write the commit helper into the workspace and return its path."""
    workspace = Path(workspace)
    bin_dir = workspace / "bin"
    bin_dir.mkdir(parents=True, exist_ok=True)
    lock = workspace / ".commit.lock"
    path = bin_dir / SCRIPT_NAME
    path.write_text(render_script(repo, lock, timeout=timeout), encoding="utf-8")
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    lock.touch(exist_ok=True)
    return path


def commit_instruction(script: str | Path) -> str:
    """The block every committing role's prompt carries."""
    return (
        "## Committing (this replaces the Committing section above)\n"
        "\n"
        "**Ignore the `git add` / `git commit` recipe given earlier in this prompt.** "
        "It states the right rule and leaves you to follow it; this run enforces the "
        "rule instead, and running the two recipes against each other is how a commit "
        "ends up carrying someone else's file.\n"
        "\n"
        "Commit through this script and through nothing else:\n"
        "\n"
        "```bash\n"
        f'{script} "<your commit message>" <path> [path...]\n'
        "```\n"
        "\n"
        "Paths are **relative to the repo root**, explicit, and complete — every "
        "file of your unit, no directories, no globs that could match a file you "
        "did not write.\n"
        "\n"
        "It takes a lock, so you may wait behind another agent; that is normal and "
        "is not an error. It then checks that the commit contains exactly the paths "
        "you named, and **undoes the commit** if it does not, leaving your work in "
        "the tree. If that happens, report it rather than retrying: it means a path "
        "you named swept in more than you meant.\n"
        "\n"
        "One commit per unit of work, so attribution and revert stay per-unit. No "
        "other git command that writes — never `push`, never a branch operation, "
        "never a rebase, never `git add -A`. No AI attribution lines in the message.\n"
    )


def lock_is_held(workspace: str | Path) -> bool:
    """Whether some process currently holds the commit lock.

    Used by the orchestrator to tell "the batch is still committing" from
    "the batch is wedged" when a dispatch overruns.
    """
    import fcntl

    lock = Path(workspace) / ".commit.lock"
    if not lock.exists():
        return False
    fd = os.open(lock, os.O_RDWR)
    try:
        fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        return True
    else:
        fcntl.flock(fd, fcntl.LOCK_UN)
        return False
    finally:
        os.close(fd)


