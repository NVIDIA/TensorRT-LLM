"""Export an InferenceX multi-node srt-slurm recipe into per-point TensorRT-LLM configs.

For every search-space point of one config key in ``inferencex-e2e/configs/nvidia-master.yaml``, this writes the
resolved engine arguments and worker environment of each role (base settings merged with the point's override):

    <out>/points.yaml                       # one summary entry per point
    <out>/<point>/{prefill,decode}.yaml     # engine arguments (``--extra-engine-args`` / ``trtllm-serve --config``)
    <out>/<point>/{prefill,decode}.env      # worker environment, one ``export`` per line

Usage:
    python3 export_srt_recipe.py --inferencex <InferenceX checkout> \
        --config-key qwen3.5-fp4-gb300-dynamo-trt-agentic-disagg --out <entry>/configs \
        [--repo <owner/name>]
"""

import argparse
import shlex
import subprocess
from pathlib import Path

import yaml

ROLES = ("prefill", "decode")
_HEADER = (
    "# SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n"
    "# SPDX-License-Identifier: Apache-2.0\n"
    "# Generated by examples/perf_reproductions/inferencex/_tools/export_srt_recipe.py from\n"
    "# {repo} {recipe} @ {commit} ({point}). Do not edit by hand.\n"
)


def _merge(base: dict, override: dict) -> dict:
    """Recursively merge ``override`` into a copy of ``base`` (override wins; lists are replaced)."""
    out = dict(base)
    for key, value in (override or {}).items():
        if isinstance(value, dict) and isinstance(out.get(key), dict):
            out[key] = _merge(out[key], value)
        else:
            out[key] = value
    return out


def _git_head(path: Path) -> str:
    return subprocess.run(
        ["git", "-C", str(path), "rev-parse", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()


def export(inferencex: Path, config_key: str, out: Path, repo: str) -> None:
    master = yaml.safe_load((inferencex / "inferencex-e2e/configs/nvidia-master.yaml").read_text())
    entry = master[config_key]
    recipe_dir = (
        inferencex
        / "inferencex-e2e/benchmarks/multi_node/srt-slurm-recipes"
        / entry["srt-recipe-dir"]
    )
    commit = _git_head(inferencex)
    points = []
    for scenario, scenario_entries in entry["scenarios"].items():
        for scenario_entry in scenario_entries:
            for point in scenario_entry["search-space"]:
                recipe_file, override_key = point["srt-recipe"].split(":")
                recipe_rel = (recipe_dir / recipe_file).relative_to(inferencex)
                recipe = yaml.safe_load((inferencex / recipe_rel).read_text())
                base, override = recipe["base"], recipe[override_key]
                name = override["name"]
                point_dir = out / name
                point_dir.mkdir(parents=True, exist_ok=True)
                header = _HEADER.format(
                    repo=repo, recipe=recipe_rel, commit=commit, point=override_key
                )
                summary = {
                    "name": name,
                    "scenario": scenario,
                    "concurrency": point["conc-list"],
                    "spec_decoding": point.get("spec-decoding"),
                    "kv_offloading": point.get("kv-offloading"),
                }
                for role in ROLES:
                    base_role = base["roles"][role]
                    over_role = (override.get("roles") or {}).get(role) or {}
                    args = _merge(base_role.get("args") or {}, over_role.get("args") or {})
                    env = {
                        **(base.get("environment") or {}),
                        **(base_role.get("env") or {}),
                        **(over_role.get("env") or {}),
                    }
                    (point_dir / f"{role}.yaml").write_text(
                        header + yaml.safe_dump(args, sort_keys=True)
                    )
                    (point_dir / f"{role}.env").write_text(
                        header
                        + "".join(
                            f"export {k}={shlex.quote(str(v))}\n" for k, v in sorted(env.items())
                        )
                    )
                    summary[role] = {
                        "workers": over_role.get("workers"),
                        "nodes": over_role.get("nodes"),
                        "gpus_per_worker": over_role.get("gpus"),
                        "tensor_parallel_size": args.get("tensor_parallel_size"),
                        "moe_expert_parallel_size": args.get("moe_expert_parallel_size"),
                        "moe_tensor_parallel_size": args.get("moe_tensor_parallel_size"),
                        "enable_attention_dp": bool(args.get("enable_attention_dp", False)),
                        "max_batch_size": args.get("max_batch_size"),
                    }
                points.append(summary)
    (out / "points.yaml").write_text(
        _HEADER.format(
            repo=repo,
            recipe=f"inferencex-e2e/configs/nvidia-master.yaml:{config_key}",
            commit=commit,
            point="all points",
        )
        + yaml.safe_dump({"image": entry["image"], "points": points}, sort_keys=False)
    )


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--inferencex", type=Path, required=True, help="InferenceX checkout at the submitted commit"
    )
    parser.add_argument(
        "--config-key", required=True, help="Key in inferencex-e2e/configs/nvidia-master.yaml"
    )
    parser.add_argument(
        "--out", type=Path, required=True, help="Output directory (the entry's configs/)"
    )
    parser.add_argument(
        "--repo",
        default="SemiAnalysisAI/InferenceX",
        help="GitHub repository that holds the checked-out commit (recorded in the headers)",
    )
    args = parser.parse_args()
    export(args.inferencex, args.config_key, args.out, args.repo)


if __name__ == "__main__":
    main()
