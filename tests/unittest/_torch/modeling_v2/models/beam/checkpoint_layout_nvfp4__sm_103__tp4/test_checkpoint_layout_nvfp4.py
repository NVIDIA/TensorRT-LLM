def test_rank_column_slices_tile_the_logical_expert(quartets) -> None:
    """The four down slices, side by side, are the stored tensor: no gap, overlap or reorder."""
    path, expected, t, _ = quartets
    catalog = loader.SafetensorsCatalog(path)
    spec = layout.QuantSpec(
        "model.layers.3.mlp.experts.7.down_proj", (5120, 2560), 3, 7, "down_proj", 1
    )
    reader = loader.TileReader(1 << 16, pin=False)
    parts, scales = [], []
    try:
        for r in range(4):
            dst = torch.empty(spec.local_packed_shape(r), dtype=torch.uint8)
            loader.read_packed_into(
                catalog, reader, spec.name + ".weight", (0, 5120), spec.packed_interval(r)[1:], dst
            )
            parts.append(dst)
            dst = torch.empty(spec.local_scale_shape(r), dtype=torch.uint8)
            loader.read_packed_into(
                catalog,
                reader,
                spec.name + ".weight_scale",
                (0, 5120),
                spec.scale_interval(r)[1:],
                dst,
            )
            scales.append(dst)
    finally:
        reader.close()
    assert torch.equal(torch.cat(parts, 1), t["down_w"])
    assert torch.equal(torch.cat(scales, 1), t["down_s"])
    # Each rank's 640 logical columns decode from exactly its 320 bytes and 40 scales.
    full = decode(t["down_w"][:8], t["down_s"][:8])
    for r in range(4):
        assert torch.equal(decode(parts[r][:8], scales[r][:8]), full[:, 640 * r : 640 * (r + 1)])


