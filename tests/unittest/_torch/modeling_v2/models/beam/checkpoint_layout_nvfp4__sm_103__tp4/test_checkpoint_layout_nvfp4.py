def test_layout_counts_dtypes_and_rank_intervals() -> None:
    specs = layout.tensor_specs(model_config())
    quant = [s for s in specs.values() if isinstance(s, layout.QuantSpec)]
    assert len(quant) == 49 * 256 * 3
    entries = layout.stored_entries(specs)
    by_dtype = {}
    for dtype, _ in entries.values():
        by_dtype[dtype] = by_dtype.get(dtype, 0) + 1
    # 636 higher-precision BF16 tensors, 98 FP32 router tensors, one quartet per projection
    assert by_dtype == {
        "BF16": 636,
        "F32": 98 + 2 * len(quant),
        "U8": len(quant),
        "F8_E4M3": len(quant),
    }
    for name, spec in specs.items():
        if isinstance(spec, layout.QuantSpec):
            continue
        if ".mlp.gate." in name:
            assert spec.stored_dtype == "F32"
        else:
            assert spec.stored_dtype == "BF16", name
    gate = specs["model.layers.3.mlp.experts.7.gate_proj"]
    down = specs["model.layers.51.mlp.experts.255.down_proj"]
    stored = gate.stored()
    assert stored["model.layers.3.mlp.experts.7.gate_proj.weight"] == ("U8", (2560, 2560))
    assert stored["model.layers.3.mlp.experts.7.gate_proj.weight_scale"] == ("F8_E4M3", (2560, 320))
    assert stored["model.layers.3.mlp.experts.7.gate_proj.weight_scale_2"] == ("F32", ())
    assert stored["model.layers.3.mlp.experts.7.gate_proj.input_scale"] == ("F32", ())
    for r in range(4):
        assert gate.interval(r) == (0, 640 * r, 640 * (r + 1))
        assert gate.packed_interval(r) == (0, 640 * r, 640 * (r + 1))
        assert gate.scale_interval(r) == (0, 640 * r, 640 * (r + 1))
        assert gate.local_packed_shape(r) == (640, 2560)
        assert gate.local_scale_shape(r) == (640, 320)
        assert down.interval(r) == (1, 640 * r, 640 * (r + 1))
        assert down.packed_interval(r) == (1, 320 * r, 320 * (r + 1))
        assert down.scale_interval(r) == (1, 40 * r, 40 * (r + 1))
        assert down.local_packed_shape(r) == (5120, 320)
        assert down.local_scale_shape(r) == (5120, 40)
    assert gate.bank == "layers.3.experts.gate" and down.bank == "layers.51.experts.down"
    layout.check_partition(specs)
    assert layout.swizzled_numel(640, 320) == 640 * 320
    assert layout.swizzled_numel(17, 40) == 128 * 40


