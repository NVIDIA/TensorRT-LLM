def _e4m3_byte(x: torch.Tensor) -> torch.Tensor:
    """FP32 -> E4M3 bytes, round to nearest even, saturating at 448 (torch's own cast)."""
    return x.clamp(max=448.0).to(torch.float8_e4m3fn).view(torch.uint8)


def _e2m1_code(x: torch.Tensor) -> torch.Tensor:
    """FP32 -> E2M1 codes, round to nearest even (ties to the even magnitude index), saturating."""
    mags = torch.tensor(_E2M1, dtype=torch.float32)
    a = x.abs().clamp(max=6.0)
    d = (a.unsqueeze(-1) - mags).abs()
    best = d.min(-1, keepdim=True).values
    ties = d == best
    idx = torch.where(ties, torch.arange(8), 100)
    even = torch.where(ties & (torch.arange(8) % 2 == 0), torch.arange(8), 100)
    pick = torch.where(ties.sum(-1) > 1, even.min(-1).values, idx.min(-1).values)
    return pick | ((x < 0) & (pick != 0)).long() * 8


def _quantize(x: torch.Tensor, s: float) -> tuple:
    """Documented static activation quantization, in the kernel's operation order: g = 1/s,
    scale = e4m3(g * (amax * (1/6))), code = e2m1(x * (1 / (scale * (1/g)))). Returns codes
    ``[M, K]``, block bytes ``[M, K/16]`` and the pre-rounding values."""
    one = torch.tensor(1.0, dtype=torch.float32)
    g = one / torch.tensor(s, dtype=torch.float32)
    blocks = x.float().cpu().view(x.shape[0], -1, 16)
    sf = _e4m3_byte(g * (blocks.abs().amax(-1) * (one / 6.0)))
    scale = _E4M3_TABLE[sf.long()].float()
    out_scale = torch.where(scale > 0, one / (scale * (one / g)), torch.zeros_like(scale))
    scaled = (blocks * out_scale.unsqueeze(-1)).view(x.shape[0], -1)
    return _e2m1_code(scaled), sf, scaled


#: Relative distance to an E2M1 midpoint inside which the kernel's approximate reciprocals may
#: round either way (the quantizer catalog entry's tie window).
_TIE = 2.0**-20


def _near_tie(scaled: torch.Tensor) -> torch.Tensor:
    mids = torch.tensor((0.25, 0.75, 1.25, 1.75, 2.5, 3.5, 5.0))
    a = scaled.abs().unsqueeze(-1)
    return ((a - mids).abs() <= _TIE * a).any(-1)


def _gemm(a_vals: torch.Tensor, w_vals: torch.Tensor, alpha: float) -> tuple:
    acc = (a_vals @ w_vals.T).float()
    out = (torch.tensor(alpha, dtype=torch.float32) * acc).to(torch.bfloat16)
    abs_dot = (a_vals.abs() @ w_vals.abs().T).float() * abs(alpha)
    return out, abs_dot


def _assert_gemm(out: torch.Tensor, a_codes, a_sf, w_packed, w_sf, alpha) -> None:
    """Kernel GEMM output vs the exact product of the same quantized operands."""
    a_vals = _E2M1_TABLE[a_codes.cpu()].view(a_codes.shape[0], -1, 16) * _E4M3_TABLE[
        a_sf.cpu().long()
    ].unsqueeze(-1)
    ref, abs_dot = _gemm(a_vals.view(a_codes.shape[0], -1), decode(w_packed, w_sf), alpha)
    r32 = ref.float()
    ulp = torch.exp2(torch.frexp(r32.abs().clamp(min=2.0**-126))[1].float() - 8)
    err = (out.cpu().float() - r32).abs()
    assert bool((err <= ulp + 2.0**-20 * abs_dot).all()), float((err / ulp).max())


@needs_sm103
@pytest.mark.parametrize("shared_fc1", [True, False])
def test_expert_provider_matches_independent_reference(shared_fc1) -> None:
    from tensorrt_llm._torch._experimental.modeling_v2.models.beam.full_model_nvfp4__sm_103__tp4.expert import (  # noqa: E501
        nvfp4_swiglu_expert,
    )

    hidden, inter, rows, n_experts, expert = 1024, 256, 7, 3, 2
    gen = torch.Generator().manual_seed(7)

    def proj(n, k, w2, s, seed):
        # every code point including signed zero; block scales spread over normal E4M3 values,
        # one all-zero block scale per projection
        packed = _bytes(n, k // 2, seed)
        sf = torch.randint(0x28, 0x48, (n, k // 16), dtype=torch.uint8, generator=gen)
        sf[0, 0] = 0
        # every other expert slot holds different codes and block scales
        bank = {
            "weight": torch.stack(
                [_bytes(n, k // 2, seed + 100 * (i + 1)) for i in range(n_experts)]
            ),
            "weight_scale": None,
            "linear_scale": torch.stack([(sf + 1 + i).to(torch.uint8) for i in range(n_experts)]),
            "input_scale": torch.full((n_experts,), s, dtype=torch.float32),
            "weight_scale_2": torch.full((n_experts,), w2, dtype=torch.float32),
        }
        bank["weight"][expert] = packed
        bank["linear_scale"][expert] = sf
        bank["g"] = torch.ones(n_experts, dtype=torch.float32) / bank["input_scale"]
        bank["alpha"] = bank["input_scale"] * bank["weight_scale_2"]
        bank["weight_scale"] = torch.stack(
            [
                torch.ops.trtllm.block_scale_interleave(bank["linear_scale"][i].cuda())
                .reshape(-1)
                .cpu()
                for i in range(n_experts)
            ]
        )
        return {key: v.cuda() for key, v in bank.items()}

    s_up = 0.0123 if shared_fc1 else 0.0171
    bank = {
        "gate": proj(inter, hidden, 2.0**-9, 0.0123, 11),
        "up": proj(inter, hidden, 3.0e-3, s_up, 12),
        "down": proj(hidden, inter, 1.25e-3, 0.0625, 13),
    }
    x = (torch.randn(rows, hidden, generator=gen) * 0.7).to(torch.bfloat16)
    x[0, :16] = 0  # one all-zero activation block
    record = []
    y = nvfp4_swiglu_expert(x.cuda(), bank, expert, shared_fc1, record)
    call = record[0]
    assert call["expert"] == expert and y.dtype == torch.bfloat16 and y.shape == (rows, hidden)
    assert (call["fc1_up"] is None) == shared_fc1

    def check_quant(codes_packed, sf_flat, src, s):
        k = src.shape[1]
        codes = unpack(codes_packed.cpu())
        sf = unswizzle(sf_flat, src.shape[0], k // 16)
        ref_codes, ref_sf, scaled = _quantize(src, s)
        assert torch.equal(sf, ref_sf)
        vals = _E2M1_TABLE[codes] * _E4M3_TABLE[sf.long()].repeat_interleave(16, 1)
        ref_vals = _E2M1_TABLE[ref_codes] * _E4M3_TABLE[ref_sf.long()].repeat_interleave(16, 1)
        differ = vals != ref_vals
        assert not bool((differ & ~_near_tie(scaled)).any())
        assert int(differ.sum()) <= 2
        return codes, sf

    fc1_codes, fc1_sf = check_quant(call["fc1"], call["sf1"], x, 0.0123)
    up_codes, up_sf = (
        (fc1_codes, fc1_sf) if shared_fc1 else check_quant(call["fc1_up"], call["sf1_up"], x, s_up)
    )
    lin = {k: bank[k]["linear_scale"][expert] for k in bank}
    _assert_gemm(
        call["gate"],
        fc1_codes,
        fc1_sf,
        bank["gate"]["weight"][expert],
        lin["gate"],
        0.0123 * 2.0**-9,
    )
    _assert_gemm(
        call["up"],
        up_codes,
        up_sf,
        bank["up"]["weight"][expert],
        lin["up"],
        float(torch.tensor(s_up, dtype=torch.float32) * torch.tensor(3.0e-3, dtype=torch.float32)),
    )
    act = (torch.nn.functional.silu(call["gate"].float()) * call["up"].float()).to(torch.bfloat16)
    assert torch.equal(act, call["act"])
    down_codes, down_sf = check_quant(call["fc2"], call["sf2"], call["act"].cpu(), 0.0625)
    _assert_gemm(
        y,
        down_codes,
        down_sf,
        bank["down"]["weight"][expert],
        lin["down"],
        float(
            torch.tensor(0.0625, dtype=torch.float32) * torch.tensor(1.25e-3, dtype=torch.float32)
        ),
    )
    # The provider used expert `expert`'s operands, not a neighbour's.
    other = nvfp4_swiglu_expert(x.cuda(), bank, (expert + 1) % n_experts, shared_fc1)
    assert not torch.equal(other, y)
