def write_checkpoint(path: str, shards: dict) -> None:
    """``shards``: file -> {name: (dtype, shape, raw bytes)}; writes the shards and the index."""
    os.makedirs(path, exist_ok=True)
    weight_map = {}
    for filename, tensors in shards.items():
        header, payload, offset = {}, [], 0
        for name, (dtype, shape, raw) in tensors.items():
            header[name] = {
                "dtype": dtype,
                "shape": list(shape),
                "data_offsets": [offset, offset + len(raw)],
            }
            payload.append(raw)
            offset += len(raw)
            weight_map[name] = filename
        blob = json.dumps(header).encode()
        with open(os.path.join(path, filename), "wb") as f:
            f.write(struct.pack("<Q", len(blob)) + blob + b"".join(payload))
    with open(os.path.join(path, "model.safetensors.index.json"), "w") as f:
        json.dump({"weight_map": weight_map}, f)


def _bytes(rows: int, cols: int, seed: int) -> torch.Tensor:
    g = torch.Generator().manual_seed(seed)
    return torch.randint(0, 256, (rows, cols), dtype=torch.uint8, generator=g)


