def recipe() -> dict:
    """A ModelOpt-style NVFP4 recipe excluding every higher-precision Linear module."""
    patterns = ["lm_head", "model.embed_tokens", "model.layers.0*", "model.layers.1.*"]
    patterns.append("model.layers.2.*")
    for layer in SPARSE:
        patterns += [f"model.layers.{layer}.mlp.gate", f"model.layers.{layer}.self_attn*"]
    return {
        "producer": {"name": "modelopt", "version": "generated"},
        "quantization": {
            "quant_algo": "NVFP4",
            "kv_cache_quant_algo": None,
            "group_size": 16,
            "exclude_modules": patterns,
        },
    }


# ------------------------------------------------------------------ independent format helpers

_E2M1 = (0.0, 0.5, 1.0, 1.5, 2.0, 3.0, 4.0, 6.0)


def e2m1(code: int) -> float:
    """E2M1 value of one 4-bit code: bit 3 sign, bits 0-2 index the magnitude table."""
    return (-1.0 if code & 8 else 1.0) * _E2M1[code & 7]


def e4m3(code: int) -> float:
    """E4M3 (fn) value of one byte from its bit fields: bias 7, subnormals, no infinities."""
    sign = -1.0 if code & 0x80 else 1.0
    exp, man = (code >> 3) & 0xF, code & 0x7
    if exp == 0xF and man == 0x7:
        return math.nan
    if exp == 0:
        return sign * man / 8.0 * 2.0**-6
    return sign * (1.0 + man / 8.0) * 2.0 ** (exp - 7)


_E4M3_TABLE = torch.tensor([e4m3(b) for b in range(256)], dtype=torch.float64)
_E2M1_TABLE = torch.tensor([e2m1(c) for c in range(16)], dtype=torch.float64)


def unpack(packed: torch.Tensor) -> torch.Tensor:
    """``[R, K/2]`` bytes -> ``[R, K]`` codes; the low nibble is the even K index."""
    p = packed.long()
    return torch.stack((p & 0xF, p >> 4), dim=-1).reshape(p.shape[0], -1)


def decode(packed: torch.Tensor, scales: torch.Tensor) -> torch.Tensor:
    """Packed codes x block scales, float64 ``[R, K]`` (global scale not applied)."""
    codes = unpack(packed.cpu())
    vals = _E2M1_TABLE[codes]
    sf = _E4M3_TABLE[scales.cpu().long()]
    return (vals.view(vals.shape[0], -1, 16) * sf.unsqueeze(-1)).view(vals.shape)


def swizzle_offset(m: int, k: int, cols: int) -> int:
    """Byte offset of block scale (row m, column k) in the 128x4 swizzled layout."""
    k_tiles = -(-cols // 4)
    return (
        (m // 128) * k_tiles * 512 + (k // 4) * 512 + (m % 32) * 16 + ((m % 128) // 32) * 4 + k % 4
    )


def unswizzle(flat: torch.Tensor, rows: int, cols: int) -> torch.Tensor:
    idx = torch.tensor(
        [swizzle_offset(m, k, cols) for m in range(rows) for k in range(cols)], dtype=torch.long
    )
    return flat.reshape(-1).cpu()[idx].view(rows, cols)


