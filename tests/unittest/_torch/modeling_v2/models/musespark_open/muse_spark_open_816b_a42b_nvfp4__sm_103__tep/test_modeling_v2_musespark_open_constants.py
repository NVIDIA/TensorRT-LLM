def _plain(value):
    """``value`` with tuples as lists and sets as lists sorted by ``repr``."""
    if isinstance(value, (set, frozenset)):
        return sorted((_plain(v) for v in value), key=repr)
    if isinstance(value, (list, tuple)):
        return [_plain(v) for v in value]
    if isinstance(value, dict):
        return {k: _plain(v) for k, v in value.items()}
    return value


@pytest.mark.parametrize("module_name", sorted(MODULE_CONSTANTS))
def test_each_module_keeps_its_constants(module_name):
    module = importlib.import_module(f"{_PKG}.{module_name}")
    for name, value in MODULE_CONSTANTS[module_name].items():
        assert hasattr(module, name), f"{module_name}.{name} is gone"
        assert _plain(getattr(module, name)) == value, f"{module_name}.{name}"
