def replicas() -> int:
    """`TRTLLM_GLM52_DEC_EXPERT_REPLICAS`, validated: 0 (off) .. `MAX_REPLICAS`; default 8."""
    r = int(os.environ.get("TRTLLM_GLM52_DEC_EXPERT_REPLICAS", "8"))
    if not 0 <= r <= MAX_REPLICAS:
        raise ValueError(f"TRTLLM_GLM52_DEC_EXPERT_REPLICAS must be in 0..{MAX_REPLICAS}, got {r}")
    return r


def hot(layer: int, r: int) -> tuple[int, ...]:
    """Layer `layer`'s `r` replica experts in slot order (empty for a layer without any)."""
    return HOT.get(int(layer), ())[:r] if r else ()
