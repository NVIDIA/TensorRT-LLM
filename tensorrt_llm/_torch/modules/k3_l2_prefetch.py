_SITES = ("pre_attn", "post_attn", "pre_moe", "in_moe", "post_moe")
_TARGETS = ("moe", "next", "attn")
_DEFAULT_CAPS = {"moe": "1-16:all", "next": "1-16:96", "attn": "1-16:64"}
_MIN_RANGE_BYTES = 16 * 1024
_ALL = -1  # uncapped

# Plain tensor attributes (decode constants and fused projection copies) that are weights.
_ATTR_ALLOW = frozenset(
    {
        "_bfa_proj_weight",
        "_qkvg_proj_weight",
        "_packed_conv_weight",
        "_w_q_t",
        "_w_k_t",
        "_w_v_t",
        "W_UK_T",
        "W_UV",
    }
)
_MOE_ROOTS = (
    "gate",
    "shared_experts",
    "routed_expert_down_proj",
    "routed_expert_up_proj",
    "routed_expert_norm",
)


def parse_caps(spec: str) -> Dict[int, int]:
    """``"1-3:96,4:64,5-16:all"`` -> {rows: cap in MiB (``_ALL`` = uncapped)}."""
    table: Dict[int, int] = {}
    for item in filter(None, (s.strip() for s in spec.split(","))):
        rows, _, cap = item.partition(":")
        lo, _, hi = rows.partition("-")
        value = _ALL if cap.strip() == "all" else int(cap)
        for m in range(int(lo), int(hi or lo) + 1):
            table[m] = value
    return table


def _tensors(value) -> List[torch.Tensor]:
    if isinstance(value, torch.Tensor):
        return [value]
    if isinstance(value, (tuple, list)):
        return [t for t in value if isinstance(t, torch.Tensor)]
    return []


def collect_weights(
    roots: Sequence[torch.nn.Module], exclude: Optional["re.Pattern"] = None
) -> List[Tuple[str, torch.Tensor]]:
    """Device weights reachable from ``roots`` in registration order, ``o_proj`` last.

    Tensors whose storage range is already covered by an earlier one (parameters that were
    repointed to row views of a fused buffer) are dropped, as are ranges below 16 KiB.
    """
    found: List[Tuple[str, torch.Tensor]] = []
    for root in roots:
        for prefix, module in root.named_modules():
            items = list(module._parameters.items()) + list(module._buffers.items())
            items += [(k, v) for k, v in vars(module).items() if k in _ATTR_ALLOW]
            for name, value in items:
                for tensor in _tensors(value):
                    found.append((f"{prefix}.{name}" if prefix else name, tensor))
    front = [x for x in found if "o_proj" not in x[0]]
    back = [x for x in found if "o_proj" in x[0]]
    out: List[Tuple[str, torch.Tensor]] = []
    spans: List[Tuple[int, int]] = []
    for name, tensor in front + back:
        if tensor.device.type != "cuda" or tensor.numel() == 0:
            continue
        if exclude is not None and exclude.search(name):
            continue
        span = 1 + sum((n - 1) * s for n, s in zip(tensor.shape, tensor.stride()))
        lo = tensor.data_ptr()
        hi = lo + span * tensor.element_size()
        if hi - lo < _MIN_RANGE_BYTES:
            continue
        if any(a <= lo and hi <= b for a, b in spans):
            continue
        spans.append((lo, hi))
        out.append((name, tensor))
    return out


class _Module:
    """The PTX module of one device, plus its launch attributes."""

    def __init__(self, device: torch.device, priority: bool):
        import cuda.bindings.driver as cuda

        self.cuda = cuda
        torch.cuda.set_device(device)
        torch.zeros(1, device=device)  # make the primary context current on this thread
        status, self.module = cuda.cuModuleLoadData(_PTX.encode() + b"\0")
        self._check(status, "cuModuleLoadData")
        status, self.function = cuda.cuModuleGetFunction(self.module, b"k3_l2_prefetch")
        self._check(status, "cuModuleGetFunction")
        status, _least, greatest = cuda.cuCtxGetStreamPriorityRange()
        self._check(status, "cuCtxGetStreamPriorityRange")
        self.greatest_priority = greatest
        self.attributes = []
        if priority:
            attribute = cuda.CUlaunchAttribute()
            attribute.id = cuda.CUlaunchAttributeID.CU_LAUNCH_ATTRIBUTE_PRIORITY
            attribute.value.priority = greatest
            self.attributes.append(attribute)

    def _check(self, status, what):
        if status != self.cuda.CUresult.CUDA_SUCCESS:
            raise RuntimeError(f"{what} failed: {status}")


class PreparedRanges:
    """An immutable (address, bytes) table and its launch configuration."""

    def __init__(self, module: _Module, weights: Sequence[torch.Tensor], byte_cap: int, grid: int):
        cuda = module.cuda
        self.weights = tuple(weights)  # keeps the storage alive for the table's lifetime
        remaining = byte_cap
        ranges = []
        for weight in self.weights:
            span = 1 + sum((n - 1) * s for n, s in zip(weight.shape, weight.stride()))
            size = span * weight.element_size()
            if byte_cap != _ALL:
                size = min(size, remaining) // 16 * 16
                remaining -= size
            if size > 0:
                ranges.append((weight.data_ptr(), size))
            if byte_cap != _ALL and remaining < 16:
                break
        self.num_ranges = len(ranges)
        self.num_bytes = sum(size for _, size in ranges)
        self.table = torch.tensor(
            ranges or [(0, 0)], dtype=torch.int64, device=self.weights[0].device
        )
        self.module = module
        config = self.config = cuda.CUlaunchConfig()
        config.gridDimX, config.gridDimY, config.gridDimZ = grid, 1, 1
        config.blockDimX, config.blockDimY, config.blockDimZ = 32, 1, 1
        config.sharedMemBytes = 0
        config.attrs = module.attributes
        config.numAttrs = len(module.attributes)
        self._pointer = ctypes.c_void_p(self.table.data_ptr())
        self._rows = ctypes.c_int(len(ranges))
        self._arguments = (ctypes.c_void_p * 2)(
            ctypes.addressof(self._pointer), ctypes.addressof(self._rows)
        )
        self._address = ctypes.addressof(self._arguments)

    def launch(self, stream_handle) -> None:
        cuda = self.module.cuda
        self.config.hStream = stream_handle
        status = cuda.cuLaunchKernelEx(self.config, self.module.function, self._address, 0)
        self.module._check(status[0] if isinstance(status, tuple) else status, "cuLaunchKernelEx")


def _site_name(layer_idx: int) -> str:
    return f"layer {layer_idx}"


class K3L2Prefetch:
    """Per-(site, layer) prefetch launches on one side stream (see the module docstring)."""

    def __init__(self, layers: Sequence[torch.nn.Module]):
        first = next(p for p in layers[0].parameters() if p.device.type == "cuda")
        self.device = first.device
        points = os.environ.get("TRTLLM_K3_L2_PREFETCH_POINTS", "pre_attn:moe,in_moe:next")
        self.points: List[Tuple[str, str]] = []
        for item in filter(None, (s.strip() for s in points.split(","))):
            site, _, target = item.partition(":")
            if site not in _SITES or target not in _TARGETS:
                raise ValueError(f"TRTLLM_K3_L2_PREFETCH_POINTS: bad entry {item!r}")
            self.points.append((site, target))
        self.caps = {
            target: parse_caps(
                os.environ.get(f"TRTLLM_K3_L2_PREFETCH_CAPS_{target.upper()}", _DEFAULT_CAPS[target])
            )
            for target in _TARGETS
        }
        grid = int(os.environ.get("TRTLLM_K3_L2_PREFETCH_GRID", "32"))
        priority = os.environ.get("TRTLLM_K3_L2_PREFETCH_PRIORITY", "1") == "1"
        exclude = os.environ.get("TRTLLM_K3_L2_PREFETCH_EXCLUDE")
        exclude = re.compile(exclude) if exclude else None
        verbose = os.environ.get("TRTLLM_K3_L2_PREFETCH_LOG", "1") == "1"

        module = _Module(self.device, priority)
        self.stream = torch.cuda.Stream(device=self.device, priority=module.greatest_priority)
        self.event = torch.cuda.Event()
        self.pending = False
        # (site, layer_idx) -> {rows: PreparedRanges}; tables are shared between rows with the
        # same (target layer, cap).
        self.tables: Dict[Tuple[str, int], Dict[int, PreparedRanges]] = {}
        cache: Dict[Tuple[str, int, int], Optional[PreparedRanges]] = {}
        by_index = {layer.layer_idx: layer for layer in layers}
        logged = set()
        total_bytes: Dict[Tuple[str, str, int], int] = {}
        for layer in layers:
            for site, target in self.points:
                source = by_index.get(layer.layer_idx + 1) if target == "next" else layer
                if source is None or (target == "moe" and not layer.is_moe):
                    continue
                weights = self._target_weights(source, target, exclude)
                if not weights:
                    continue
                if verbose and (target, source.is_kda) not in logged:
                    logged.add((target, source.is_kda))
                    logger.info(
                        f"K3 L2 prefetch {site}:{target} layer {source.layer_idx} "
                        f"({'KDA' if source.is_kda else 'MLA'}): "
                        + ", ".join(
                            f"{n}[{tuple(w.shape)} {str(w.dtype).split('.')[-1]} "
                            f"{w.numel() * w.element_size() / 2**20:.1f}MiB]"
                            for n, w in weights
                        )
                    )
                per_rows = {}
                for rows, cap in self.caps[target].items():
                    if cap == 0:
                        continue
                    key = (target, source.layer_idx, cap)
                    if key not in cache:
                        cache[key] = PreparedRanges(
                            module, [w for _, w in weights], cap * 2**20 if cap > 0 else _ALL, grid
                        )
                    per_rows[rows] = cache[key]
                    total_bytes[(site, target, rows)] = (
                        total_bytes.get((site, target, rows), 0) + cache[key].num_bytes
                    )
                self.tables[(site, layer.layer_idx)] = {
                    **self.tables.get((site, layer.layer_idx), {}),
                    **{(target, r): t for r, t in per_rows.items()},
                }
        self._selftest(module)
        torch.cuda.synchronize(self.device)
        if verbose:
            for (site, target, rows), nbytes in sorted(total_bytes.items()):
                if rows in (1, 2, 6, 12, 16):
                    logger.info(
                        f"K3 L2 prefetch {site}:{target} rows={rows}: "
                        f"{nbytes / 2**20:.1f} MiB over all layers"
                    )
        logger.info(
            f"K3 L2 prefetch enabled: points={self.points} grid={grid} priority={priority}"
        )

    @staticmethod
    def _target_weights(layer, target: str, exclude) -> List[Tuple[str, torch.Tensor]]:
        if target == "moe":
            if layer.is_moe:
                moe = layer.block_sparse_moe
                roots = [getattr(moe, n) for n in _MOE_ROOTS if hasattr(moe, n)]
            else:
                roots = [layer.mlp]
        else:
            roots = [layer.linear_attn if layer.is_kda else layer.self_attn]
        weights = collect_weights(roots, exclude)
        if target == "moe":
            return weights
        # Source projections whose rows were copied into a fused projection the decode reads
        # (separate storage), and prefill-only weights.
        dead = []
        attention = roots[0]
        if hasattr(attention, "qkvg_proj"):
            dead.append(r"^(q|k|v|g)_proj\.")
        mixer = getattr(attention, "mixer", None)
        if mixer is not None and hasattr(mixer, "g_fused_a_proj"):
            dead.append(r"^mixer\.(g_proj|kv_a_proj_with_mqa|kv_b_proj)\.")
        if dead:
            pattern = re.compile("|".join(dead))
            weights = [(n, w) for n, w in weights if not pattern.search(n)]
        return weights

    def _selftest(self, module: _Module) -> None:
        for per_rows in self.tables.values():
            for table in per_rows.values():
                table.launch(self.cuda_stream(self.stream))
                return

    @staticmethod
    def cuda_stream(stream: torch.cuda.Stream):
        import cuda.bindings.driver as cuda

        return cuda.CUstream(stream.cuda_stream)

    def fork(self, site: str, layer_idx: int, rows: int) -> None:
        per_rows = self.tables.get((site, layer_idx))
        if not per_rows:
            return
        current = torch.cuda.current_stream(self.device)
        launches = [t for (target, r), t in per_rows.items() if r == rows]
        if not launches:
            return
        self.event.record(current)
        self.stream.wait_event(self.event)
        self.pending = True
        handle = self.cuda_stream(self.stream)
        for table in launches:
            table.launch(handle)

    def join(self) -> None:
        if self.pending:
            torch.cuda.current_stream(self.device).wait_stream(self.stream)
            self.pending = False
