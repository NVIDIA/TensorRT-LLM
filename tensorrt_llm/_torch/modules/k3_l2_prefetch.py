"""L2 weight prefetch side stream for the Kimi K3 decode step (``TRTLLM_K3_L2_PREFETCH=1``).

Small-M decode kernels are bound by cold HBM weight streaming. At fixed points of each
decoder layer a tiny kernel runs on a high-priority side stream and issues
``cp.async.bulk.prefetch.L2`` over the byte ranges of weights that later kernels read, so
those kernels start with warm L2. The side stream forks from the main stream (event) at
each point and ``join()`` makes the main stream wait for it at the end of the step, so a
captured CUDA graph always rejoins the side stream. All tables are built eagerly (outside
graph capture); a fork only records an event and launches one kernel.

Sites (where a fork happens in ``KimiLinearDecoderLayer.forward``):
  pre_attn   after the input norm, before the attention
  post_attn  after the attention, before the post-attention mix
  pre_moe    before the MoE / MLP block
  in_moe     inside the routed branch of the MoE, right before the routed experts
  post_moe   after the MoE / MLP block (the layer's output)
Targets (what is prefetched):
  moe   this layer's dense MoE weights (router, latent projections, shared expert; the
        dense MLP of layer 0)
  next  the next layer's attention weights
  attn  this layer's attention weights
Environment:
  TRTLLM_K3_L2_PREFETCH=1               enable (off by default)
  TRTLLM_K3_L2_PREFETCH_POINTS          comma list of site:target, default
                                        "pre_attn:moe,in_moe:next"
  TRTLLM_K3_L2_PREFETCH_CAPS_<TARGET>   per-row-count byte cap table in MiB,
                                        "1-16:96,17-32:0"; "all" = uncapped, 0 = no
                                        prefetch. Defaults: MOE "1-16:all",
                                        NEXT "1-16:96", ATTN "1-16:64". Rows beyond the
                                        table never prefetch.
  TRTLLM_K3_L2_PREFETCH_GRID            CTAs of 32 threads (default 32)
  TRTLLM_K3_L2_PREFETCH_PRIORITY        1 (default): highest launch priority
  TRTLLM_K3_L2_PREFETCH_EXCLUDE         regex of parameter names to leave out
  TRTLLM_K3_L2_PREFETCH_LOG             1: log the composition of the first tables
"""

