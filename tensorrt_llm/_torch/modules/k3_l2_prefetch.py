# k3_l2_prefetch.cu, compiled with nvrtc (CUDA 12.8) to PTX ISA 8.7 for compute_90; the
# driver JIT-compiles it for the running GPU. Every thread walks a device table of
# (address, bytes) ranges and issues 16-KiB chunks in a rotating assignment over the grid.
_KERNEL_SOURCE = r"""
extern "C" __global__ void k3_l2_prefetch(const long long *ranges, int rows) {
  const long long workers = (long long)gridDim.x * blockDim.x;
  const long long worker = (long long)blockIdx.x * blockDim.x + threadIdx.x;
  long long phase = 0;
  for (int row = 0; row < rows; ++row) {
    const long long base = ranges[2 * row];
    const long long nbytes = ranges[2 * row + 1];
    if (base == 0 || nbytes <= 0) continue;
    const long long chunks = (nbytes + 16383) / 16384;
    long long index = worker - phase % workers;
    if (index < 0) index += workers;
    for (; index < chunks; index += workers) {
      const long long offset = index * 16384;
      long long size = nbytes - offset;
      if (size > 16384) size = 16384;
      size &= ~15LL;
      if (size > 0) {
        const unsigned long long address = (unsigned long long)(base + offset) & ~15ULL;
        asm volatile("cp.async.bulk.prefetch.L2.global [%0], %1;"
                     :: "l"(address), "r"((unsigned int)size) : "memory");
      }
    }
    phase += chunks;
  }
}
"""

