_BACKEND_ENV = "TRTLLM_LOW_M_GEMM_BACKEND"

# M-dimension profiles generated by the TRT-LLM AutoTuner.
_M_TUNING_BUCKETS: tuple[int, ...] = (1, 2, 3, 4, 5, 6, 7, 8, 16, 32)
# The direct kernel uses the exact runtime M as its row tile through this bound.
_MAX_EXACT_DIRECT_M = 8


def _map_m_to_tuning_bucket(m: int) -> int:
    """Keep row-specialized direct shapes exact and bucket larger M values."""
    if m <= _MAX_EXACT_DIRECT_M:
        return m
    return next((b for b in _M_TUNING_BUCKETS if b >= m), _M_TUNING_BUCKETS[-1])


_M_DIM_SPEC = DynamicTensorSpec(
    input_idx=0,
    dim_idx=0,
    gen_tuning_buckets=_M_TUNING_BUCKETS,
    map_to_tuning_buckets=_map_m_to_tuning_bucket,
)

# Authoritative M upper bound, duplicated from the FlashInfer kernels' _MAX_M
# to avoid importing nvidia-cutlass-dsl on every import of this module.
_MAX_M = 32

_AUTOTUNER_OP_NAME = "trtllm::low_m_bf16_gemm"
_FP8_AUTOTUNER_OP_NAME = "trtllm::low_m_fp8_gemm"

# A module that holds a plain [N, K] BF16 weight but is not a Linear -- a
# hand-written MoE router gate, say -- opts into the race by setting this
# attribute and calling apply_low_m_gemm() itself.
LOW_M_GEMM_OPT_IN_ATTR = "_low_m_gemm_opt_in"

# Env-var strings that activate the low-M GEMM path.
# "cublas" / "cublaslt" were legacy aliases meaning "disabled"; anything
# unrecognised raises ValueError.
_ENABLED_VALUES = frozenset({"auto", "cute-dsl", "flashinfer", "flashinfer-cute-dsl"})
_DISABLED_VALUES = frozenset({"", "0", "none", "off", "cublas", "cublaslt"})


def _parse_enabled() -> bool:
    """Return True when ``TRTLLM_LOW_M_GEMM_BACKEND`` activates the low-M GEMM path."""
    raw = os.environ.get(_BACKEND_ENV, "off").strip().lower().replace("_", "-")
    if raw in _ENABLED_VALUES:
        return True
    if raw in _DISABLED_VALUES:
        return False
    raise ValueError(
        f"Invalid {_BACKEND_ENV}={os.environ.get(_BACKEND_ENV)!r}; "
        f"expected one of: off, auto, cute-dsl."
    )


@functools.lru_cache(maxsize=None)
def _current_sm(device: torch.device) -> int:
    """Return the SM version (e.g. 100 for B200, 103 for GB300) for *device*.

    Kept as a named lru_cache'd function so unit tests can monkeypatch it without
    touching torch.cuda internals.
    """
    major, minor = torch.cuda.get_device_capability(device)
    return major * 10 + minor


# ---------------------------------------------------------------------------
# TunableRunner for cuBLAS (baseline / fallback competitor)
# ---------------------------------------------------------------------------


class _CuBLASGemmRunner(TunableRunner):
    """AutoTuner runner that delegates to cuBLAS via ``torch.mm`` / ``torch.addmm``.

    Included in every AutoTuner race so that low-M kernels are only chosen
    when they actually beat cuBLAS on the observed (M, K, N) shape.  For shapes
    where the custom kernels are slower (e.g. large-N / small-K on certain
    hardware), this runner wins and the low-M path is silently skipped —
    no performance regression regardless of env-var setting.

    The sentinel tactic ``("cublas",)`` is JSON-serialisable so the AutoTuner
    cache persists it correctly across warmup calls.

    inputs: ``[a [M,K] BF16, b_t [K,N] BF16]``; optional ``bias [N]`` kwarg.
    """

    _TACTIC = ("cublas",)

    def __init__(self, *, has_bias: bool) -> None:
        self.has_bias = has_bias

    def unique_id(self) -> tuple:
        return ("cublas", bool(self.has_bias))

    def get_valid_tactics(
        self,
        inputs: List[torch.Tensor],
        profile: Any,
        **kwargs: Any,
    ) -> List[Any]:
        return [self._TACTIC]

    def forward(
        self,
        inputs: List[torch.Tensor],
        *,
        tactic: Any = None,
        do_preparation: bool = False,
        **kwargs: Any,
    ) -> torch.Tensor:
        a, b_t = inputs[0], inputs[1]  # a=[M,K], b_t=[K,N]
        bias = kwargs.get("bias")
        out = kwargs.get("out")
        if out is None:
            out = torch.empty((int(a.shape[0]), int(b_t.shape[1])), dtype=a.dtype, device=a.device)
        # torch.mm / torch.addmm write directly into ``out`` with no extra copy.
        if bias is not None:
            torch.addmm(bias, a, b_t, out=out)
        else:
            torch.mm(a, b_t, out=out)
        return out


# ---------------------------------------------------------------------------
# TunableRunner for the SM10x direct (SIMT register-prefetch) BF16 GEMM
# ---------------------------------------------------------------------------


class _DirectGemmRunner(TunableRunner):
    """AutoTuner runner for the SM10x CuTe-DSL direct (SIMT) BF16 kernel.

    The direct kernel prefetches the entire K dimension of each weight row into
    registers and accumulates with scalar FP32, avoiding TMA and TMEM.  It
    outperforms the split-K kernel at ``M=1, K=8192, N≤4608`` and a few other
    narrow shapes; the AutoTuner selects it only when it wins the timed race.

    **Bias is not supported** — ``get_valid_tactics`` returns ``[]`` when
    ``bias`` is present so the AutoTuner never records a direct-kernel win for
    biased calls.

    inputs: ``[a [M,K] BF16, b_t [K,N] col-major BF16]``.
    """

    def __init__(self, *, pdl: bool) -> None:
        self.pdl = pdl

    def unique_id(self) -> tuple:
        return ("direct", bool(self.pdl))

    def is_tactic_compatible(
        self,
        inputs: list[torch.Tensor],
        tactic: object,
    ) -> bool:
        """Return whether a cached direct tactic can serve the runtime shape."""
        from flashinfer.gemm.kernels.dense_bf16_gemm_direct import DirectTactic, validate_tactic

        a, b_t = inputs[0], inputs[1]
        m, k, n = int(a.shape[0]), int(a.shape[1]), int(b_t.shape[1])
        try:
            validate_tactic(DirectTactic(*tactic), m, n, k)
        except (TypeError, ValueError):
            return False
        return True

    def get_valid_tactics(
        self,
        inputs: List[torch.Tensor],
        profile: Any,
        **kwargs: Any,
    ) -> List[Any]:
        """Return JSON-serialisable ``(block_size, outputs_per_block, rows_per_block)`` tuples.

        Returns an empty list when *bias* is present — the direct kernel has no
        bias support so it should never win an autotuned bias call.
        """
        import dataclasses

        if kwargs.get("bias") is not None:
            return []

        from flashinfer.gemm.kernels.dense_bf16_gemm_direct import autotune_tactics, default_tactic

        a, b_t = inputs[0], inputs[1]
        m, k, n = int(a.shape[0]), int(a.shape[1]), int(b_t.shape[1])
        seen: dict = {}
        try:
            for t in (default_tactic(m, n, k), *autotune_tactics(m, n, k)):
                seen.setdefault(dataclasses.astuple(t), None)
        except ValueError:
            pass
        return list(seen)

    def forward(
        self,
        inputs: List[torch.Tensor],
        *,
        tactic: Any = -1,
        do_preparation: bool = False,
        **kwargs: Any,
    ) -> torch.Tensor:
        from flashinfer.gemm.kernels.dense_bf16_gemm_direct import (
            DirectTactic,
            default_tactic,
            run_direct_dense,
        )

        a, b_t = inputs[0], inputs[1]
        m, k, n = int(a.shape[0]), int(a.shape[1]), int(b_t.shape[1])
        actual_tactic = default_tactic(m, n, k) if tactic == -1 else DirectTactic(*tactic)
        out = kwargs.get("out")
        if out is None:
            out = torch.empty((m, n), dtype=a.dtype, device=a.device)
        # b_t is [K, N] col-major (weight.t()), which is what run_direct_dense
        # expects as its 'b' argument (b.T will be [N, K] row-major for the kernel).
        return run_direct_dense(a, b_t, out, self.pdl, actual_tactic)


# ---------------------------------------------------------------------------
# TunableRunner for the built-in SM10x split-K BF16 GEMM
# ---------------------------------------------------------------------------


class _SplitKGemmRunner(TunableRunner):
    """AutoTuner runner for the built-in SM10x (Blackwell) CuTe-DSL split-K BF16 kernel.

    One instance per ``(has_bias, pdl)`` so the AutoTuner keeps separate
    best-tactic cache entries for each variant.

    inputs: ``[a [M,K] BF16, b_t [K,N] BF16]``; ``bias`` passed as a kwarg.
    """

    def __init__(self, *, has_bias: bool, pdl: bool) -> None:
        self.has_bias = has_bias
        self.pdl = pdl

    def unique_id(self) -> tuple:
        return (bool(self.has_bias), bool(self.pdl))

    def get_valid_tactics(
        self,
        inputs: List[torch.Tensor],
        profile: Any,
        **kwargs: Any,
    ) -> List[Any]:
        """Return JSON-serialisable ``(mma_m, mma_n, split_k, ab_stages)`` 4-tuples."""
        import dataclasses

        from flashinfer.gemm.kernels.dense_bf16_gemm_sm100_splitk import (
            autotune_tactics,
            default_tactic,
        )

        a, b_t = inputs[0], inputs[1]
        m, k, n = int(a.shape[0]), int(a.shape[1]), int(b_t.shape[1])
        # Guard against zero-width outputs: default_tactic raises ValueError for n<=0,
        # which would propagate past AutoTuner's per-tactic exception handling and
        # bypass the cuBLAS fallback.
        if n <= 0:
            return []
        # Deduplicate: heuristic default first, then enumerated candidates.
        seen: dict = {}
        for t in (default_tactic(m, n, k), *autotune_tactics(m, n, k)):
            seen.setdefault(dataclasses.astuple(t), None)
        return list(seen)

    def forward(
        self,
        inputs: List[torch.Tensor],
        *,
        tactic: Any = -1,
        do_preparation: bool = False,
        **kwargs: Any,
    ) -> torch.Tensor:
        from flashinfer.gemm.kernels.dense_bf16_gemm_sm100_splitk import (
            SplitKTactic,
            default_tactic,
            run_splitk_dense,
        )

        a, b_t = inputs[0], inputs[1]
        bias = kwargs.get("bias")
        m, k, n = int(a.shape[0]), int(a.shape[1]), int(b_t.shape[1])
        actual_tactic = default_tactic(m, n, k) if tactic == -1 else SplitKTactic(*tactic)
        # Prefer a pre-allocated buffer supplied by the caller so the kernel
        # writes to a stable device address that a surrounding CUDA graph can
        # safely replay.  Fall back to per-call allocation when no buffer is
        # provided (e.g. during AutoTuner profiling).
        out = kwargs.get("out")
        if out is None:
            out = torch.empty((m, n), dtype=a.dtype, device=a.device)
        return run_splitk_dense(a, b_t, bias, out, self.pdl, actual_tactic)


# ---------------------------------------------------------------------------
# TunableRunners for the SM10x warp-MMA GEMM (BF16, and FP8 per-tensor weights)
# ---------------------------------------------------------------------------


def _warp_mma_tactics(m: int, k: int, n: int, fp8: bool) -> List[Any]:
    if not low_m_mma_gemm.warp_mma_supported() or k % 64 or n % 8 or not 1 <= m <= _MAX_M:
        return []
    return low_m_mma_gemm.candidate_tactics(m, n, k, fp8)


class _WarpMmaGemmRunner(TunableRunner):
    """AutoTuner runner for the warp-MMA kernel (``modules/low_m_mma_gemm.py``) in the BF16 race.

    It prefetches each CTA's weight tiles into registers and splits K over warps (optionally over a CTA
    cluster); tactics are ``(k_warps, n_tiles, ksplit, swap_ab, min_blocks)`` around its heuristic.

    inputs: ``[a [M,K] BF16, b_t [K,N] col-major BF16]``; no bias.
    """

    def unique_id(self) -> tuple:
        return ("warp_mma",)

    def get_valid_tactics(
        self,
        inputs: List[torch.Tensor],
        profile: Any,
        **kwargs: Any,
    ) -> List[Any]:
        if kwargs.get("bias") is not None:
            return []
        a, b_t = inputs[0], inputs[1]
        return _warp_mma_tactics(int(a.shape[0]), int(a.shape[1]), int(b_t.shape[1]), fp8=False)

    def forward(
        self,
        inputs: List[torch.Tensor],
        *,
        tactic: Any = -1,
        do_preparation: bool = False,
        **kwargs: Any,
    ) -> torch.Tensor:
        a, b_t = inputs[0], inputs[1]
        return low_m_mma_gemm.low_m_mma_gemm(
            x16=a, w_bf16=b_t.t(), tactic_bf16=None if tactic == -1 else tuple(tactic)
        )


class _CuBLASFp8GemmRunner(TunableRunner):
    """Baseline of the FP8 race: what ``FP8QDQLinearMethod`` runs, the static per-tensor quantization of a BF16
    input (``quantize``) then cuBLAS scaled-mm.

    inputs: ``[a [M,K] BF16 or E4M3, w [N,K] E4M3, weight_scale, input_scale]``; ``out_dtype`` kwarg.
    """

    _TACTIC = ("cublas",)

    def __init__(self, *, quantize: bool) -> None:
        self.quantize = quantize

    def unique_id(self) -> tuple:
        return ("cublas_fp8", self.quantize)

    def get_valid_tactics(
        self,
        inputs: List[torch.Tensor],
        profile: Any,
        **kwargs: Any,
    ) -> List[Any]:
        return [self._TACTIC]

    def forward(
        self,
        inputs: List[torch.Tensor],
        *,
        tactic: Any = None,
        do_preparation: bool = False,
        **kwargs: Any,
    ) -> torch.Tensor:
        a, w, weight_scale, input_scale = inputs
        if self.quantize:
            a, _ = torch.ops.tensorrt_llm.static_quantize_e4m3_per_tensor(a, input_scale)
        return torch.ops.trtllm.cublas_scaled_mm(
            a,
            w.t(),
            scale_a=input_scale,
            scale_b=weight_scale,
            bias=None,
            out_dtype=kwargs.get("out_dtype", torch.bfloat16),
        )


class _WarpMmaFp8GemmRunner(TunableRunner):
    """AutoTuner runner for the warp-MMA kernel in the FP8 race: E4M3 activations, or BF16 activations
    quantized in registers with the static input scale (``quantize``), bitwise the baseline's quantization.

    inputs: as ``_CuBLASFp8GemmRunner``.
    """

    def __init__(self, *, quantize: bool, single_cta_k: bool = False) -> None:
        self.quantize = quantize
        # Only tactics without split-K (ksplit 1): the ones a conv1d epilogue can run with.
        self.single_cta_k = single_cta_k

    def unique_id(self) -> tuple:
        return ("warp_mma_fp8", self.quantize) + (("single_cta_k",) if self.single_cta_k else ())

    def get_valid_tactics(
        self,
        inputs: List[torch.Tensor],
        profile: Any,
        **kwargs: Any,
    ) -> List[Any]:
        a, w = inputs[0], inputs[1]
        tactics = _warp_mma_tactics(int(a.shape[0]), int(a.shape[1]), int(w.shape[0]), fp8=True)
        return [t for t in tactics if t[2] == 1] if self.single_cta_k else tactics

    def forward(
        self,
        inputs: List[torch.Tensor],
        *,
        tactic: Any = -1,
        do_preparation: bool = False,
        **kwargs: Any,
    ) -> torch.Tensor:
        a, w, weight_scale, input_scale = inputs
        return low_m_mma_gemm.low_m_mma_gemm(
            x16=a if self.quantize else None,
            x8=None if self.quantize else a,
            w_fp8=w,
            weight_scale=weight_scale,
            input_scale=input_scale,
            fp8_act="quant" if self.quantize else "fp8",
            out_dtype=kwargs.get("out_dtype", torch.bfloat16),
            tactic=None if tactic == -1 else tuple(tactic),
        )


