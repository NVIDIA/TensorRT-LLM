# ``LOW_M_GEMM_ACTIVE`` is read at import time from the env var so that
# ``linear.py`` can gate the hot path with a single bool check.
LOW_M_GEMM_ACTIVE = _parse_enabled()


def low_m_gemm_takes_rows(module: Optional[torch.nn.Module], rows: int) -> bool:
    """Whether a GEMM of ``rows`` rows takes the low-M path: the global enable flag (or a dispatcher attached to
    ``module``) and the M upper bound (``_MAX_M``, or the module's own ceiling, ``LowMGemmDispatcher.limit_rows``)."""
    dispatcher = getattr(module, "_low_m_gemm_dispatcher", None)
    if not LOW_M_GEMM_ACTIVE and dispatcher is None:
        return False
    # The AutoTuner race is host code that torch.compile cannot trace.
    if torch.compiler.is_compiling() or rows > _MAX_M:
        return False
    return dispatcher is None or dispatcher.takes_rows(module, rows)


def _should_apply_low_m_gemm(input: torch.Tensor, module: Optional[torch.nn.Module] = None) -> bool:
    """Fast pre-filter: :func:`low_m_gemm_takes_rows` for the rows of ``input``, after the enable flag (or a
    dispatcher attached to ``module``) and the compile check, which cost no shape reads."""
    if not LOW_M_GEMM_ACTIVE and getattr(module, "_low_m_gemm_dispatcher", None) is None:
        return False
    if input.ndim < 1 or torch.compiler.is_compiling():
        return False
    k = int(input.shape[-1])
    if k <= 0:
        return False
    return low_m_gemm_takes_rows(module, input.numel() // k)


class LowMGemmDispatcher:
    """Route eligible BF16 GEMMs to the best available kernel for each shape.

    On every forward call the TRT-LLM :class:`AutoTuner` races two low-M
    SM10x (Blackwell) CuTe-DSL kernels (split-K tensor-core and SIMT direct)
    against cuBLAS (``torch.mm``) and caches the winner per ``(M-bucket, K, N)``
    shape.  Custom kernels are only chosen when they are strictly faster than
    cuBLAS for the observed tensor geometry — shapes where neither custom kernel
    wins automatically fall back to cuBLAS without any manual tuning.

    Lifecycle
    ---------
    1. **Model loading**: call :meth:`attach` once per model to label every
       ``Linear`` submodule and bind this dispatcher to it.  This is lightweight
       (no GPU resources allocated).
    2. **First forward / warmup**: :meth:`apply` calls :meth:`_init_runners`
       lazily on the first invocation.  The AutoTuner then profiles each
       (M-bucket, K, N) shape it encounters and caches the winner.
    """

    # The direct kernel's coarse buckets offer only tactics that serve every row count of the bucket.
    whole_bucket_direct_tiles: bool = False
    # Per module: the most rows it takes on the low-M path (limit_rows); None: no limits.
    _max_rows: Optional[Dict[torch.nn.Module, int]] = None

    def __init__(self) -> None:
        # _prepared: runners + TuningConfig have been created (set by _init_runners).
        self._prepared = False
        # _attached: modules have been labelled (set by attach).
        self._attached = False
        self._runner_no_bias: Optional[_SplitKGemmRunner] = None
        self._runner_with_bias: Optional[_SplitKGemmRunner] = None
        # Direct (SIMT register-prefetch) runner — no-bias only; cuBLAS handles
        # biased calls when neither low-M kernel wins.
        self._direct: Optional[_DirectGemmRunner] = None
        # Warp-MMA runner (no bias) and the FP8 race's runners, keyed by
        # whether the input is quantized in the kernel (BF16 input).
        self._warp_mma: Optional[_WarpMmaGemmRunner] = None
        self._fp8_runners: dict = {}
        # The FP8 race of callers that need a single-CTA K warp-MMA tactic: that runner alone.
        self._fp8_runners_single_cta_k: dict = {}
        # cuBLAS runners compete in every AutoTuner race as a safety baseline.
        self._cublas_no_bias: Optional[_CuBLASGemmRunner] = None
        self._cublas_with_bias: Optional[_CuBLASGemmRunner] = None
        self._tuning_config: Optional[TuningConfig] = None
        # Pre-allocated output buffers keyed by ``(m_bucket, n)``.  Populated
        # lazily outside of CUDA-graph capture so the kernel always writes to a
        # stable device address that a surrounding CUDA graph can safely replay.
        self._output_buffers: dict = {}
        # Saved ``force`` flag from :meth:`attach` so :meth:`_init_runners` can
        # honour it without requiring an extra argument.
        self._force: bool = False
        # Tune on every rank: ranks of the group see different shapes (attention DP), so a rank-local cache
        # hit must not skip a collective a peer enters.
        self.per_rank_tuning: bool = False

    def attach(
        self,
        model: torch.nn.Module,
        force: bool = False,
    ) -> None:
        """Label every ``Linear`` or opt-in submodule and bind this dispatcher to it.

        This is the **model-loading phase**: it iterates the module tree once,
        assigns ``_low_m_gemm_name`` and ``_low_m_gemm_dispatcher`` on each
        eligible submodule, and returns immediately.  No GPU resources are
        allocated; runners are created lazily on the first :meth:`apply` call.

        Args:
            model: The model whose eligible submodules should be labelled.
            force: Attach even when ``TRTLLM_LOW_M_GEMM_BACKEND`` is not set.
                Reserved for callers that activate the dispatcher via a
                mechanism other than the env var (e.g. a future LLM arg).
        """
        if self._attached:
            return
        self._attached = True
        self._force = force
        if not LOW_M_GEMM_ACTIVE and not force:
            return
        for name, module in model.named_modules():
            if getattr(module, "_low_m_gemm_dispatcher", None) is not None:
                # A model that prepared its own dispatcher (e.g. Qwen3.5, with its row limits and tactics) keeps it:
                # the loader's generic one must not replace it.
                continue
            if module.__class__.__name__.endswith("Linear") or getattr(
                module, LOW_M_GEMM_OPT_IN_ATTR, False
            ):
                module._low_m_gemm_name = name
                # Bind this dispatcher so apply_low_m_gemm can reach the
                # per-engine instance without a global singleton.
                module._low_m_gemm_dispatcher = self

    def _init_runners(self) -> None:
        """Create AutoTuner runners and the tuning config (lazy, first-use init).

        Called automatically by :meth:`apply` on the first forward pass.
        Separated from :meth:`attach` so that GPU-resource allocation happens
        during the warmup phase rather than at model-load time.
        """
        if self._prepared:
            return
        if not LOW_M_GEMM_ACTIVE and not self._force:
            # Stay unprepared: a later forced call must still create the runners.
            return
        pdl = get_env_enable_pdl()
        self._runner_no_bias = _SplitKGemmRunner(has_bias=False, pdl=pdl)
        self._runner_with_bias = _SplitKGemmRunner(has_bias=True, pdl=pdl)
        # Direct SIMT runner: no-bias only; wins for M=1 with narrow N on K=8192.
        self._direct = _DirectGemmRunner(pdl=pdl, whole_bucket_tiles=self.whole_bucket_direct_tiles)
        self._warp_mma = _WarpMmaGemmRunner()
        # cuBLAS runners — always included as competitors so the AutoTuner can
        # fall back to cuBLAS for shapes where neither custom kernel is fastest.
        self._cublas_no_bias = _CuBLASGemmRunner(has_bias=False)
        self._cublas_with_bias = _CuBLASGemmRunner(has_bias=True)
        # cuBLAS first: the cache-miss fallback (runners[0]) is the stock path.
        self._fp8_runners = {
            quantize: [
                _CuBLASFp8GemmRunner(quantize=quantize),
                _WarpMmaFp8GemmRunner(quantize=quantize),
            ]
            for quantize in (False, True)
        }
        self._fp8_runners_single_cta_k = {
            quantize: [_WarpMmaFp8GemmRunner(quantize=quantize, single_cta_k=True)]
            for quantize in (False, True)
        }
        self._tuning_config = TuningConfig(
            dynamic_tensor_specs=(_M_DIM_SPEC,),
            use_cold_l2_cache=True,
            # Time device work as the decode CUDA graphs replay it, PDL launches
            # included: eager timing adds each runner's host launch cost, which
            # exceeds these kernels' device time and the graphs never pay.
            use_cuda_graph=True,
            # The ranks of the group split the race: each builds and times its
            # share of every runner's tactics, and the merge keeps the fastest,
            # so every rank runs the same winner (ranks running different
            # kernels would let the slowest set the pace of each collective).
            # The direct kernel is built per exact (M, N, K, tactic), so one
            # rank racing every candidate alone takes most of warmup. Under
            # attention DP the ranks' shapes differ, so each tunes its own.
            distributed_tuning_strategy=(
                DistributedTuningStrategy.INDEPENDENT
                if self.per_rank_tuning
                else DistributedTuningStrategy.PARALLEL
            ),
        )
        # Mark prepared only after all runners and the tuning config exist so the
        # invariant "_prepared implies runners are non-None" always holds.
        self._prepared = True
        logger.info(
            "Low-M BF16 GEMM dispatcher initialised "
            "(split-K tensor-core + SIMT direct vs cuBLAS AutoTuner; best kernel per shape)."
        )

    def limit_rows(self, module: torch.nn.Module, max_rows: int) -> None:
        """Keep ``module`` off the low-M path above ``max_rows`` rows."""
        if self._max_rows is None:
            self._max_rows = {}
        self._max_rows[module] = max_rows

    def takes_rows(self, module: torch.nn.Module, rows: int) -> bool:
        """Whether ``module`` takes the low-M path at ``rows`` rows under its ``limit_rows`` ceiling."""
        if self._max_rows is None:
            return True
        return rows <= self._max_rows.get(module, _MAX_M)

    def prepare(
        self,
        model: torch.nn.Module,
        force: bool = False,
    ) -> None:
        """Attach the dispatcher and eagerly initialise runners.

        Convenience wrapper that calls :meth:`attach` followed by
        :meth:`_init_runners`.  Prefer calling :meth:`attach` at model-load
        time and letting :meth:`_init_runners` trigger lazily on the first
        forward pass; use this method only when immediate runner initialisation
        is required (e.g. in unit tests).

        Args:
            model: The model whose eligible submodules should be labelled.
            force: Initialise runners even when ``TRTLLM_LOW_M_GEMM_BACKEND``
                is not set.  Reserved for callers that activate the low-M
                GEMM path via a mechanism other than the env var (e.g. a future
                LLM arg).
        """
        self.attach(model, force=force)
        self._init_runners()

    @staticmethod
    def _is_candidate_shape(
        input_tensor: torch.Tensor,
        weight: torch.Tensor,
        bias: Optional[torch.Tensor],
    ) -> bool:
        if (
            torch.is_grad_enabled()
            or input_tensor.ndim < 1
            or weight.ndim != 2
            or not input_tensor.is_cuda
            or not weight.is_cuda
            or input_tensor.device != weight.device
            or input_tensor.dtype != torch.bfloat16
            or weight.dtype != torch.bfloat16
            or not input_tensor.is_contiguous()
            or not weight.is_contiguous()
        ):
            return False
        k = int(input_tensor.shape[-1])
        if k <= 0 or int(weight.shape[1]) != k or k % 128:
            return False
        if not 1 <= input_tensor.numel() // k <= _MAX_M:
            return False
        if input_tensor.data_ptr() % 32 or weight.data_ptr() % 32:
            return False
        if bias is not None and (
            not bias.is_cuda
            or bias.device != input_tensor.device
            or bias.dtype != torch.bfloat16
            or bias.shape != (weight.shape[0],)
            or not bias.is_contiguous()
        ):
            return False
        return is_sm_100f(_current_sm(input_tensor.device))

    def apply(
        self,
        module: torch.nn.Module,
        input_tensor: torch.Tensor,
        weight: torch.Tensor,
        bias: Optional[torch.Tensor],
        force_active: bool = False,
    ) -> Optional[torch.Tensor]:
        """Return a low-M GEMM result, or ``None`` to fall through to the normal path.

        Args:
            force_active: When ``True`` the low-M path is attempted even if
                ``TRTLLM_LOW_M_GEMM_BACKEND`` is not set.  Reserved for callers
                that activate it via a mechanism other than the env var (e.g. a
                future ``use_low_m_low_latency_gemm`` LLM arg).
        """
        if not LOW_M_GEMM_ACTIVE and not (force_active or self._force):
            return None
        if torch.compiler.is_compiling():
            return None
        if not self._prepared:
            # Unit tests and direct callers that bypass ModelEngine / attach().
            # Never drop the force of attach(): the runners must exist past the gate above.
            self._force = self._force or force_active
            self._init_runners()
        if not self._is_candidate_shape(input_tensor, weight, bias):
            return None
        # _is_candidate_shape() confirmed grad is disabled; detach weight only
        # (it may carry requires_grad=True even in inference mode).
        input_2d = input_tensor.view(-1, input_tensor.shape[-1])
        weight_t = weight.detach().t()  # [N, K] → [K, N] col-major view
        bias_d = bias.detach() if bias is not None else None
        has_bias = bias_d is not None
        # Race cuBLAS, split-K tensor-core, and SIMT direct; the AutoTuner caches
        # the winner per shape.  cuBLAS is listed first so that the cache-miss
        # fallback (runners[0]) always lands on the safe baseline rather than
        # running a custom kernel on an untuned shape.
        splitk_runner = self._runner_with_bias if has_bias else self._runner_no_bias
        cublas_runner = self._cublas_with_bias if has_bias else self._cublas_no_bias
        runners: List = [cublas_runner, splitk_runner]
        if not has_bias:
            # Include the direct SIMT and warp-MMA runners for unbiased calls;
            # they return [] for biased inputs so it is safe to always pass,
            # but excluding them for biased calls keeps the race concise.
            runners.append(self._direct)
            runners.append(self._warp_mma)
        best_runner, best_tactic = AutoTuner.get().choose_one(
            _AUTOTUNER_OP_NAME,
            runners,
            self._tuning_config,
            [input_2d, weight_t],
            bias=bias_d,
        )
        # Larger M values still share coarse buckets. Revalidate direct tactics
        # before launching the tail-less kernel and use the guaranteed baseline
        # when a cached row tile is incompatible with the runtime M.
        if best_runner is self._direct and not self._direct.is_tactic_compatible(
            [input_2d, weight_t], best_tactic
        ):
            best_runner = cublas_runner
            best_tactic = -1
        # Cache output storage outside capture, keyed by module to prevent
        # same-shaped projections from sharing a destination. During capture,
        # each invocation needs its own output: a module may run repeatedly
        # while callers retain earlier results (for example, draft logits).
        m = int(input_2d.shape[0])
        n = int(weight.shape[0])
        m_bucket = next((b for b in _M_TUNING_BUCKETS if b >= m), _M_TUNING_BUCKETS[-1])
        module_key = getattr(module, "_low_m_gemm_name", str(id(module)))
        buf_key = (module_key, m_bucket, n)
        is_capturing = torch.cuda.is_current_stream_capturing()
        if is_capturing:
            out_buf = torch.empty((m, n), dtype=input_2d.dtype, device=input_2d.device)
        else:
            if buf_key not in self._output_buffers:
                self._output_buffers[buf_key] = torch.empty(
                    (m_bucket, n), dtype=torch.bfloat16, device=input_2d.device
                )
            out_buf = self._output_buffers[buf_key][:m, :]
        out = best_runner([input_2d, weight_t], tactic=best_tactic, bias=bias_d, out=out_buf)
        out_view = out.view(*input_tensor.shape[:-1], weight.shape[0])
        # Clone when using the shared cached buffer (i.e. outside CUDA-graph capture)
        # so that callers retaining the result across repeated forward passes —
        # e.g. the speculative-decoding drafting loop that appends logits before
        # torch.stack() — receive an independent copy rather than a view that the
        # next call silently overwrites.  Inside a capture window out_buf is already
        # a fresh per-call allocation, so no clone is needed there.
        if not is_capturing:
            return out_view.clone()
        return out_view

    def _fp8_choice(
        self,
        input_2d: torch.Tensor,
        weight: torch.Tensor,
        weight_scale: torch.Tensor,
        input_scale: torch.Tensor,
        out_dtype: torch.dtype,
        single_cta_k: bool = False,
    ):
        """(runner, tactic, inputs) of the FP8 race for this call, or None when the shape is no candidate.
        ``single_cta_k``: the race of the warp-MMA tactics without split-K alone."""
        if not self._prepared:
            self._init_runners()
        k = int(input_2d.shape[-1])
        if (
            torch.is_grad_enabled()
            or input_2d.dim() != 2
            or not 1 <= int(input_2d.shape[0]) <= _MAX_M
            or input_2d.dtype not in (torch.bfloat16, torch.float8_e4m3fn)
            or weight.dtype != torch.float8_e4m3fn
            or int(weight.shape[1]) != k
            or not input_2d.is_contiguous()
            or not weight.is_contiguous()
            or not low_m_mma_gemm.warp_mma_supported()
        ):
            return None
        quantize = input_2d.dtype != torch.float8_e4m3fn
        inputs = [input_2d, weight, weight_scale, input_scale]
        runner, tactic = AutoTuner.get().choose_one(
            _FP8_AUTOTUNER_OP_NAME,
            (self._fp8_runners_single_cta_k if single_cta_k else self._fp8_runners)[quantize],
            self._tuning_config,
            inputs,
            out_dtype=out_dtype,
        )
        return runner, tactic, inputs

    def apply_fp8(
        self,
        input_tensor: torch.Tensor,
        weight: torch.Tensor,
        weight_scale: torch.Tensor,
        input_scale: torch.Tensor,
        out_dtype: torch.dtype,
        single_cta_k: bool = False,
    ) -> Optional[torch.Tensor]:
        """``input @ weight.T`` for an FP8 per-tensor (static input scale) projection from the FP8 race, or None
        for the normal path. A BF16 input is quantized with ``input_scale``. ``single_cta_k``: as
        :meth:`warp_mma_tactic`."""
        if not LOW_M_GEMM_ACTIVE and not self._force:
            return None
        if torch.compiler.is_compiling():
            return None
        input_2d = input_tensor.reshape(-1, input_tensor.shape[-1])
        choice = self._fp8_choice(
            input_2d, weight, weight_scale, input_scale, out_dtype, single_cta_k
        )
        if choice is None:
            return None
        runner, tactic, inputs = choice
        out = runner(inputs, tactic=tactic, out_dtype=out_dtype)
        return out.view(*input_tensor.shape[:-1], weight.shape[0])

    def warp_mma_tactic(
        self,
        num_rows: int,
        weight: torch.Tensor,
        weight_scale: Optional[torch.Tensor] = None,
        input_scale: Optional[torch.Tensor] = None,
        quantize: bool = True,
        single_cta_k: bool = False,
    ) -> Optional[Tuple[int, ...]]:
        """The warp-MMA tactic this dispatcher's race picked for ``num_rows`` rows of the projection ``weight``
        (the FP8 race for an E4M3 weight, with a BF16 input when ``quantize``; else the BF16 race), or None:
        another runner won, the shape was not tuned, or the race is being tuned (callers then run the plain
        projection, which tunes it).

        Fused users launch the warp-MMA kernel with this tactic, so they run where the plain projection would,
        with its summation order.

        ``single_cta_k`` (E4M3 weight): the race of the warp-MMA tactics without split-K alone, for a fused user
        whose epilogue needs one CTA per output tile (``apply_fp8(..., single_cta_k=True)`` tunes it); an untuned
        shape takes the heuristic tactic, so the fused kernel always runs outside tuning.
        """
        # The race is host code that torch.compile cannot trace.
        if torch.compiler.is_compiling():
            return None
        tuner = AutoTuner.get()
        if (not LOW_M_GEMM_ACTIVE and not self._force) or tuner.is_tuning_mode:
            return None
        if not 1 <= num_rows <= _MAX_M or not low_m_mma_gemm.warp_mma_supported():
            return None
        if not self._prepared:
            self._init_runners()
        n, k = int(weight.shape[0]), int(weight.shape[1])
        if weight.dtype == torch.float8_e4m3fn:
            op = _FP8_AUTOTUNER_OP_NAME
            runners = (self._fp8_runners_single_cta_k if single_cta_k else self._fp8_runners)[
                quantize
            ]
            shapes = (
                torch.Size((num_rows, k)),
                weight.shape,
                weight_scale.shape,
                input_scale.shape,
            )
        else:
            op = _AUTOTUNER_OP_NAME
            runners = [self._cublas_no_bias, self._runner_no_bias, self._direct, self._warp_mma]
            shapes = (torch.Size((num_rows, k)), torch.Size((k, n)))
        hit, runner_id, tactic, _ = tuner.profiling_cache.search_cache(
            op, runners, shapes, self._tuning_config
        )
        if not hit or runners[runner_id] is not runners[-1] or tactic == -1:
            single = single_cta_k and weight.dtype == torch.float8_e4m3fn
            return low_m_mma_gemm.default_tactic(num_rows, n, k) if single else None
        return tuple(tactic)


def low_m_gemm_dispatcher(module: torch.nn.Module) -> Optional[LowMGemmDispatcher]:
    """The dispatcher of ``module`` (attached by ``prepare_low_m_gemm``), the process-global one when
    ``TRTLLM_LOW_M_GEMM_BACKEND`` activates it, else None."""
    dispatcher = getattr(module, "_low_m_gemm_dispatcher", None)
    if dispatcher is None and LOW_M_GEMM_ACTIVE:
        dispatcher = _DISPATCHER
    return dispatcher


# Process-global fallback dispatcher used by callers that bypass
# ``prepare_low_m_gemm`` (e.g. unit tests or direct kernel benchmarks).
# Production code paths receive a *per-engine* dispatcher created by
# ``prepare_low_m_gemm`` and stored on each Linear module.
_DISPATCHER = LowMGemmDispatcher()


def prepare_low_m_gemm(
    model: torch.nn.Module,
    force: bool = False,
    per_rank_tuning: bool = False,
    whole_bucket_direct_tiles: bool = False,
) -> LowMGemmDispatcher:
    """Create a per-engine dispatcher and attach it to every eligible submodule.

    Each call creates a fresh :class:`LowMGemmDispatcher` so that two model
    engines running in the same process (e.g. target + draft in speculative
    decoding) own independent dispatcher state and never share output buffers.

    This function performs only the lightweight **attach** phase: it labels every
    ``Linear`` or opt-in submodule with ``_low_m_gemm_name`` and ``_low_m_gemm_dispatcher``
    so :func:`apply_low_m_gemm` can reach the per-engine instance without a
    global reference.  AutoTuner runners are initialised lazily on the first
    forward pass (warmup), not here.

    Args:
        model: Model whose eligible submodules will be labelled.
        force: Attach even when ``TRTLLM_LOW_M_GEMM_BACKEND`` is not set
            (reserved for callers that activate the dispatcher via a future
            LLM arg).
        per_rank_tuning: Tune each rank on its own (attention DP: the ranks'
            projections see different token counts).
        whole_bucket_direct_tiles: Race the direct kernel at the coarse M
            buckets only with tactics that serve every row count of the bucket.

    Returns:
        The newly created :class:`LowMGemmDispatcher` for this engine.
    """
    dispatcher = LowMGemmDispatcher()
    dispatcher.per_rank_tuning = per_rank_tuning
    dispatcher.whole_bucket_direct_tiles = whole_bucket_direct_tiles
    dispatcher.attach(model, force=force)
    return dispatcher


def apply_low_m_gemm(
    module: torch.nn.Module,
    input_tensor: torch.Tensor,
    weight: torch.Tensor,
    bias: Optional[torch.Tensor],
    force_active: bool = False,
) -> Optional[torch.Tensor]:
    """Return a low-M BF16 result, or ``None`` for the normal path.

    Uses the per-engine :class:`LowMGemmDispatcher` stored on *module* by
    :func:`prepare_low_m_gemm`, falling back to the global ``_DISPATCHER``
    for callers that bypass preparation (e.g. unit tests).

    Args:
        force_active: Attempt the low-M path even when
            ``TRTLLM_LOW_M_GEMM_BACKEND`` is not set (passed through to
            :meth:`LowMGemmDispatcher.apply`).
    """
    dispatcher: LowMGemmDispatcher = getattr(module, "_low_m_gemm_dispatcher", _DISPATCHER)
    return dispatcher.apply(module, input_tensor, weight, bias, force_active=force_active)


